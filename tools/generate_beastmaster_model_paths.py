#!/usr/bin/env python3
"""Generate Custom/Client addons needed/DC-Collection/Data/BeastmasterModelPaths.lua.

[creatureDisplayId] -> client .m2 path for the Beastmaster (hunter tameable-pet
catalog) 3D preview. Model:SetCreature()/SetDisplayInfo() are unreliable on this
client build even for genuine stock display ids (see Data/PetModelPaths.lua and
Data/MountModelPaths.lua, which hit the same issue) -- Model:SetModel(<m2 path>) +
SetLight is the only renderer proven reliable across the addon, so every preview
panel needs its own displayId -> .m2 path table. Mirrors Data/PetModelPaths.lua.

Source: a displayId list exported from `dc_beastmaster_pets` JOIN
`creature_template_model` (world DB; not available as a CSV in this repo, so the
list is passed in via --ids), resolved through Custom/CSV DBC/CreatureDisplayInfo.csv
(displayId -> ModelID) + CreatureModelData.csv (ModelID -> ModelName).
Regenerate whenever the Beastmaster roster (dc_beastmaster_pets) changes.
"""
from __future__ import annotations
import argparse
import csv
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
CSVDBC = REPO / "Custom/CSV DBC"
OUT = REPO / "Custom/Client addons needed/DC-Collection/Data/BeastmasterModelPaths.lua"


def load_csv(path):
    with open(path, newline="", encoding="utf-8") as f:
        r = csv.reader(f)
        h = next(r)
        ix = {n: i for i, n in enumerate(h)}
        return [row for row in r if row], ix


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ids", required=True,
                     help="CSV file with one column 'displayId', one id per row (header required)")
    a = ap.parse_args()

    cdi_rows, cdi_ix = load_csv(CSVDBC / "CreatureDisplayInfo.csv")
    cmd_rows, cmd_ix = load_csv(CSVDBC / "CreatureModelData.csv")

    disp2model = {}
    for row in cdi_rows:
        try:
            did = int(row[cdi_ix["ID"]])
        except (ValueError, IndexError):
            continue
        disp2model[did] = row[cdi_ix["ModelID"]]

    model2name = {}
    for row in cmd_rows:
        try:
            model2name[row[cmd_ix["ID"]]] = row[cmd_ix["ModelName"]]
        except IndexError:
            pass

    id_rows, id_ix = load_csv(Path(a.ids))
    di = id_ix.get("displayId", 0)
    wanted = []
    for row in id_rows:
        try:
            wanted.append(int(row[di]))
        except (ValueError, IndexError):
            continue

    paths = {}
    missing = []
    for did in sorted(set(wanted)):
        model_id = disp2model.get(did)
        name = model2name.get(model_id) if model_id else None
        if name:
            paths[did] = name
        else:
            missing.append(did)

    lines = [
        "--[[",
        "    DC-Collection Data/BeastmasterModelPaths.lua",
        "    ===============================================",
        "",
        "    [creatureDisplayId] -> client .m2 path for the Beastmaster hunter-pet",
        "    catalog 3D preview. Model:SetCreature()/SetDisplayInfo() are unreliable on",
        "    this client build (see Data/PetModelPaths.lua) even for genuine stock",
        "    display ids, so Model:SetModel(<path>) + SetLight is the reliable renderer",
        "    and needs this per-display lookup. AUTO-GENERATED by",
        "    tools/generate_beastmaster_model_paths.py from Custom/CSV DBC/",
        "    CreatureDisplayInfo + CreatureModelData; regenerate when the",
        "    dc_beastmaster_pets roster changes. Do not edit by hand.",
        "]]",
        "",
        "local DC = DCCollection",
        "",
        "DC.BeastmasterModelPaths = DC.BeastmasterModelPaths or {",
    ]
    for did in sorted(paths):
        esc = paths[did].replace("\\", "\\\\")
        lines.append('    [%d] = "%s",' % (did, esc))
    lines.append("}")
    lines.append("")

    OUT.write_text("\n".join(lines), newline="\n", encoding="utf-8")
    print("WROTE", OUT)
    print("  beastmaster display paths:", len(paths))
    print("  missing (no CreatureDisplayInfo/CreatureModelData match):", len(missing))
    if missing:
        print("   ", missing[:20], "..." if len(missing) > 20 else "")


if __name__ == "__main__":
    main()
