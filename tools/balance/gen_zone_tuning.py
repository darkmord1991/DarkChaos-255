#!/usr/bin/env python3
"""
Retune the normal mobs of the level 81-160 zones from damage-meter measurements.

Maps 750 (levels 81-129) and 751 (130-160) were measured with the DC damage meter
(dc_bench_fight, run 2, 2026-11-15: solo fights of bots against rank-0 mobs, after the
class rank rollout). Against the stock level-80 reference (Northrend: 11-12 second
fights, 0.8% of the player's health lost per second) the solo fights there took 16-33
seconds and cost up to 1.4% health per second. Map 750's mobs carry health and damage
modifiers of 1.4-2.6 (Northrend's: about 1.2).

For each 5-level bucket of mob level this scales the mobs' HealthModifier toward a
TARGET_SECONDS fight and their DamageModifier toward TARGET_LOSS health per second:
factor = target / measured, never above 1 (nothing gets harder) and never below
MIN_FACTOR. A bucket measured in fewer than FULL_WEIGHT_FIGHTS fights is blended toward
its map's average; a bucket without fights takes the map average. The factors apply to
the modifiers the mobs had before this file first ran, kept in
`dc_balance_mob_tune_backup`, so re-running gives the same result and a new measurement
can simply be fed in and the file regenerated.

Only rank-0, attackable creatures that can enter combat, without an npcflag or a guard-type
name, spawned on one of the two maps and nowhere else, are touched.

Usage:
    python tools/balance/gen_zone_tuning.py --out <file.sql>
"""

import argparse
from pathlib import Path

TARGET_SECONDS = 14.0
TARGET_LOSS = 0.85
MIN_FACTOR = 0.5
FULL_WEIGHT_FIGHTS = 100

# Not mobs: non-attackable, immune to players or to NPCs, not selectable (UNIT_FLAG_*). Creatures with an npcflag
# (quest givers, vendors) and guard-type names are skipped as well: they are not what players fight.
NOT_A_MOB_FLAGS = 0x2 | 0x100 | 0x200 | 0x2000000

# Not mobs either: CREATURE_FLAG_EXTRA_CANNOT_ENTER_COMBAT. Quest objects such as Creeper Egg and Webbed Victim carry
# it; they never enter combat, so they regenerate as if idle and are meant to have a single hit point.
NOT_A_MOB_FLAGS_EXTRA = 0x2000

# The level range each map is tuned for: (lowest bucket, highest bucket).
MAP_LEVELS = {750: (80, 125), 751: (130, 155)}

# Entries whose DamageModifier is set outright after the bucket factors, because their bucket's factor leaves them
# far off. 2026-11-21 (pending world rev_1795287822533137100): the level-90 Spitelash Myrmidon / Battlemaster /
# Enchantress clones and the Horde Invader on 750 killed bots in 23-34% of their fights at 1.543; 1.0 is the stock
# Azshara value (the stock originals kill 0% of level 52-56 bots).
DAMAGE_OVERRIDES = {3606196: 1.0, 3607885: 1.0, 3607886: 1.0, 3633334: 1.0}

# Meter run 2 (2026-11-15), rank-0 targets, solo, fights of 3 s or more:
# (map, bucket of target level) -> (fights, average fight seconds, % own health lost per second)
MEASURED = {
    (750, 80): (1401, 15.8, 0.71),
    (750, 85): (278, 17.5, 0.72),
    (750, 90): (668, 24.8, 1.39),
    (750, 95): (141, 25.9, 1.27),
    (750, 100): (92, 18.3, 0.62),
    (750, 105): (65, 16.6, 0.98),
    (750, 110): (158, 22.0, 0.88),
    (750, 115): (24, 33.5, 0.71),
    (750, 125): (13, 49.6, 1.51),
    (751, 130): (345, 21.9, 0.90),
    (751, 135): (629, 25.0, 1.07),
    (751, 140): (678, 21.0, 1.33),
    (751, 145): (620, 18.4, 1.35),
    (751, 150): (806, 18.8, 1.23),
    (751, 155): (448, 20.0, 1.35),
}


def clamp(value):
    return max(MIN_FACTOR, min(1.0, value))


def factors():
    out = {}
    for map_id, (low, high) in MAP_LEVELS.items():
        rows = [(fights, seconds, loss) for (m, _bucket), (fights, seconds, loss) in MEASURED.items() if m == map_id]
        total = sum(fights for fights, _s, _l in rows)
        map_seconds = sum(fights * seconds for fights, seconds, _l in rows) / total
        map_loss = sum(fights * loss for fights, _s, loss in rows) / total
        for bucket in range(low, high + 1, 5):
            fights, seconds, loss = MEASURED.get((map_id, bucket), (0, map_seconds, map_loss))
            weight = min(1.0, fights / FULL_WEIGHT_FIGHTS)
            seconds = weight * seconds + (1 - weight) * map_seconds
            loss = weight * loss + (1 - weight) * map_loss
            out[(map_id, bucket)] = (round(clamp(TARGET_SECONDS / seconds), 3), round(clamp(TARGET_LOSS / loss), 3),
                                     fights, seconds, loss)
    return out


def render_sql(table):
    out = []
    out.append("-- DarkChaos: normal mobs of maps 750 (81-129) and 751 (130-160) retuned toward %d-second solo fights"
               % TARGET_SECONDS)
    out.append("-- (generated by tools/balance/gen_zone_tuning.py from damage meter run 2, 2026-11-15)")
    out.append("--")
    out.append("-- Stock level 80 (Northrend) solo fights last 11-12 seconds and cost 0.8% of the player's health per")
    out.append("-- second; on these maps they took 16-33 seconds at up to 1.4%. Per 5-level bucket of mob level,")
    out.append("-- HealthModifier is scaled toward %d-second fights and DamageModifier toward %.2f%% health lost per"
               % (TARGET_SECONDS, TARGET_LOSS))
    out.append("-- second, by factors between %.1f and 1 (no mob gets harder). Only rank-0 creatures spawned on one"
               % MIN_FACTOR)
    out.append("-- of the two maps and nowhere else are changed; elites, bosses and shared templates are not.")
    out.append("--")
    out.append("-- The factors apply to the modifiers a mob had before this file first ran, which it keeps in")
    out.append("-- dc_balance_mob_tune_backup: re-running gives the same result. To undo, copy the backup's two")
    out.append("-- columns back into creature_template. Apply to acore_world, then restart the worldserver.")
    out.append("--")
    out.append("-- map bucket  fights  seconds  loss%/s  -> health x  damage x")
    for (map_id, bucket), (hp, dmg, fights, seconds, loss) in sorted(table.items()):
        out.append("-- %3d %6d %7d %8.1f %8.2f %11.3f %9.3f" % (map_id, bucket, fights, seconds, loss, hp, dmg))
    out.append("")
    out.append("CREATE TABLE IF NOT EXISTS `dc_balance_mob_tune_backup` (`entry` INT UNSIGNED NOT NULL PRIMARY KEY, "
               "`HealthModifier` FLOAT NOT NULL, `DamageModifier` FLOAT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 "
               "COLLATE=utf8mb4_unicode_ci;")
    out.append("")
    out.append("DROP TEMPORARY TABLE IF EXISTS `dc_tmp_mob_tune`;")
    out.append("CREATE TEMPORARY TABLE `dc_tmp_mob_tune` (`map` SMALLINT UNSIGNED NOT NULL, `bucket` TINYINT UNSIGNED "
               "NOT NULL, `hp_factor` FLOAT NOT NULL, `dmg_factor` FLOAT NOT NULL, PRIMARY KEY (`map`, `bucket`)) "
               "ENGINE=InnoDB;")
    out.append("DELETE FROM `dc_tmp_mob_tune`;")
    out.append("INSERT INTO `dc_tmp_mob_tune` (`map`, `bucket`, `hp_factor`, `dmg_factor`) VALUES %s;" % ", ".join(
        "(%d, %d, %.3f, %.3f)" % (map_id, bucket, hp, dmg) for (map_id, bucket), (hp, dmg, *_r) in sorted(table.items())))
    out.append("")
    out.append("-- The mobs: rank 0, attackable, no npcflag, not a guard, every spawn on the same one of the two maps,")
    out.append("-- level inside that map's tuned range.")
    out.append("DROP TEMPORARY TABLE IF EXISTS `dc_tmp_mob_entries`;")
    out.append("CREATE TEMPORARY TABLE `dc_tmp_mob_entries` (`entry` INT UNSIGNED NOT NULL PRIMARY KEY, `map` SMALLINT "
               "UNSIGNED NOT NULL, `bucket` TINYINT UNSIGNED NOT NULL) ENGINE=InnoDB;")
    for map_id, (low, high) in sorted(MAP_LEVELS.items()):
        out.append("DELETE FROM `dc_tmp_mob_entries` WHERE `map` = %d;" % map_id)
        out.append("INSERT INTO `dc_tmp_mob_entries` (`entry`, `map`, `bucket`) SELECT DISTINCT `ct`.`entry`, %d, "
                   "`ct`.`minlevel` - `ct`.`minlevel` %% 5 FROM `creature_template` AS `ct` JOIN `creature` AS `c` "
                   "ON `c`.`id` = `ct`.`entry` AND `c`.`map` = %d WHERE `ct`.`rank` = 0 AND `ct`.`minlevel` BETWEEN %d "
                   "AND %d AND `ct`.`npcflag` = 0 AND (`ct`.`unit_flags` & %d) = 0 AND (`ct`.`flags_extra` & %d) = 0 "
                   "AND `ct`.`name` NOT LIKE '%%Guard%%' "
                   "AND `ct`.`name` NOT LIKE '%%Sentinel%%' AND `ct`.`name` NOT LIKE '%%Defender%%' "
                   "AND `ct`.`name` NOT LIKE '%%Grunt%%' AND NOT EXISTS (SELECT 1 FROM `creature` AS `o` WHERE `o`.`id` = `ct`.`entry` AND `o`.`map` "
                   "<> %d);" % (map_id, map_id, low, high + 4, NOT_A_MOB_FLAGS, NOT_A_MOB_FLAGS_EXTRA, map_id))
    out.append("")
    out.append("-- Keep each mob's modifiers from before the first run (INSERT IGNORE keeps the first copy; the DELETE")
    out.append("-- removes nothing and only satisfies the codestyle rule that every INSERT follows a DELETE).")
    out.append("DELETE FROM `dc_balance_mob_tune_backup` WHERE `entry` = 0;")
    out.append("INSERT IGNORE INTO `dc_balance_mob_tune_backup` (`entry`, `HealthModifier`, `DamageModifier`) SELECT "
               "`ct`.`entry`, `ct`.`HealthModifier`, `ct`.`DamageModifier` FROM `creature_template` AS `ct` "
               "JOIN `dc_tmp_mob_entries` AS `e` ON `e`.`entry` = `ct`.`entry`;")
    out.append("")
    out.append("UPDATE `creature_template` AS `ct` JOIN `dc_tmp_mob_entries` AS `e` ON `e`.`entry` = `ct`.`entry` "
               "JOIN `dc_balance_mob_tune_backup` AS `b` ON `b`.`entry` = `ct`.`entry` JOIN `dc_tmp_mob_tune` AS `t` "
               "ON `t`.`map` = `e`.`map` AND `t`.`bucket` = `e`.`bucket` SET `ct`.`HealthModifier` = `b`.`HealthModifier` "
               "* `t`.`hp_factor`, `ct`.`DamageModifier` = `b`.`DamageModifier` * `t`.`dmg_factor`;")
    out.append("")
    if DAMAGE_OVERRIDES:
        out.append("-- Set outright, see DAMAGE_OVERRIDES in the generator.")
        for value in sorted(set(DAMAGE_OVERRIDES.values())):
            entries = sorted(e for e, v in DAMAGE_OVERRIDES.items() if v == value)
            out.append("UPDATE `creature_template` SET `DamageModifier` = %g WHERE `entry` IN (%s);"
                       % (value, ", ".join(str(e) for e in entries)))
        out.append("")
    out.append("DROP TEMPORARY TABLE `dc_tmp_mob_entries`;")
    out.append("DROP TEMPORARY TABLE `dc_tmp_mob_tune`;")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    table = factors()
    args.out.write_text(render_sql(table), encoding="utf-8", newline="\n")
    for (map_id, bucket), (hp, dmg, fights, seconds, loss) in sorted(table.items()):
        print("%d %3d  fights %4d  %5.1f s  %4.2f %%/s  -> health x%.3f  damage x%.3f"
              % (map_id, bucket, fights, seconds, loss, hp, dmg))


if __name__ == "__main__":
    main()
