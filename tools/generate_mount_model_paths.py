#!/usr/bin/env python3
"""Generate Custom/Client addons needed/DC-Collection/Data/MountModelPaths.lua.

[displayId] -> client .m2 path for the mount 3D preview. The DC-Collection mount
preview model is a DressUpModel that has NO SetDisplayInfo, and custom server
creature entries (3461xxx) are not shipped to the client, so SetCreature() can't
render unowned customs. SetModel(<m2 path>) IS reliable (DressUpModel, + SetLight),
so the addon needs the per-display .m2 path. Mirrors Data/PetModelPaths.lua.

Source: Custom/CSV DBC/CreatureDisplayInfo.csv (displayId -> ModelID) +
CreatureModelData.csv (ModelID -> ModelName), restricted to custom mount displays
(>= 500000) that appear in the DC Collection mount catalog (DCCollectionSource.csv).
Regenerate whenever custom mounts change.
"""
from __future__ import annotations
import csv
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
CSVDBC = REPO / "Custom/CSV DBC"
OUT = REPO / "Custom/Client addons needed/DC-Collection/Data/MountModelPaths.lua"
CUSTOM_FLOOR = 500000


def load_csv(path):
    with open(path, newline="", encoding="utf-8") as f:
        r = csv.reader(f)
        h = next(r)
        ix = {n: i for i, n in enumerate(h)}
        return [row for row in r if row], ix


def main():
    cdi_rows, cdi_ix = load_csv(CSVDBC / "CreatureDisplayInfo.csv")
    cmd_rows, cmd_ix = load_csv(CSVDBC / "CreatureModelData.csv")

    disp2model = {}
    for row in cdi_rows:
        try:
            did = int(row[cdi_ix["ID"]])
        except (ValueError, IndexError):
            continue
        if did >= CUSTOM_FLOOR:
            disp2model[did] = row[cdi_ix["ModelID"]]

    model2name = {}
    for row in cmd_rows:
        try:
            model2name[row[cmd_ix["ID"]]] = row[cmd_ix["ModelName"]]
        except IndexError:
            pass

    # mount display ids from the regenerated collection source (collectiontype 1)
    mount_disps = set()
    src = CSVDBC / "CDBC/DCCollectionSource.csv"
    if src.exists():
        srows, six = load_csv(src)
        ct = six.get("CollectionType", 1)
        di = six.get("DisplayID", 9)
        for row in srows:
            try:
                if row[ct] == "1":
                    mount_disps.add(int(row[di]))
            except (ValueError, IndexError):
                pass
    # fall back to every custom display if the source csv is unavailable
    if not mount_disps:
        mount_disps = set(disp2model.keys())

    paths = {}
    for did in sorted(mount_disps):
        if did < CUSTOM_FLOOR:
            continue
        model_id = disp2model.get(did)
        name = model2name.get(model_id) if model_id else None
        if name:
            paths[did] = name

    lines = [
        "--[[",
        "    DC-Collection Data/MountModelPaths.lua",
        "    =====================================",
        "",
        "    [creatureDisplayId] -> client .m2 path for the mount 3D preview.",
        "    The mount preview DressUpModel has NO SetDisplayInfo and custom creature",
        "    entries (3461xxx) are not in the client, so the only reliable renderer for",
        "    unowned custom mounts is Model:SetModel(<path>) + SetLight (a raw SetModel'd",
        "    M2 renders black without a light). Owned/stock mounts still use",
        "    SetCreature(companion). AUTO-GENERATED by tools/generate_mount_model_paths.py",
        "    from Custom/CSV DBC/ CreatureDisplayInfo + CreatureModelData; regenerate when",
        "    custom mounts change. Do not edit by hand.",
        "]]",
        "",
        "local DC = DCCollection",
        "",
        "DC.MountModelPaths = DC.MountModelPaths or {",
    ]
    for did in sorted(paths):
        esc = paths[did].replace("\\", "\\\\")
        lines.append('    [%d] = "%s",' % (did, esc))
    lines.append("}")
    lines.append("")

    OUT.write_text("\n".join(lines), newline="\n", encoding="utf-8")
    print("WROTE", OUT)
    print("  custom mount display paths:", len(paths))
    sample = list(sorted(paths))[:3]
    for did in sample:
        print("   ", did, "->", paths[did])


if __name__ == "__main__":
    main()
