#!/usr/bin/env python3
"""Regenerate DC-Collection/Data/FormModelPaths.lua: shapeshift-skin display id -> M2 path.

The forms preview (UI/FormFrame.lua) renders a skin with Model:SetModel(path), because SetDisplayInfo/SetCreature do
not reliably render on the 3.3.5a client. Every model id of world table dc_shapeshift_form_skins needs an entry.

Inputs:
  --catalog FILE   "form<TAB>model" lines of the live table, e.g.
                   ssh <db host> 'mysql -N -e "SELECT form, model FROM acore_world.dc_shapeshift_form_skins"'
  --sql FILE ...   pending SQL files that INSERT into dc_shapeshift_form_skins (rows not applied yet)
  --dbc DIR        folder with CreatureDisplayInfo.dbc and CreatureModelData.dbc (Custom/DBCs or the server folder)
  --out FILE       the Lua file to write
Display ids that do not resolve to a model are reported and left out.
"""
import argparse
import re
import struct


def load_dbc(path):
    raw = open(path, "rb").read()
    magic, nrec, _nfield, recsize, _strsize = struct.unpack_from("<4s4I", raw, 0)
    if magic != b"WDBC":
        raise SystemExit(path + ": not a WDBC file")
    strings = raw[20 + nrec * recsize:]
    rows = [struct.unpack_from("<%dI" % (recsize // 4), raw, 20 + i * recsize) for i in range(nrec)]
    return rows, strings


def dbc_string(strings, offset):
    end = strings.find(b"\0", offset)
    return strings[offset:end].decode("utf-8", errors="replace")


def model_paths(dbc_dir):
    cdi, _ = load_dbc(dbc_dir + "/CreatureDisplayInfo.dbc")
    cmd, cmd_strings = load_dbc(dbc_dir + "/CreatureModelData.dbc")
    models = {row[0]: dbc_string(cmd_strings, row[2]) for row in cmd}
    paths = {}
    for row in cdi:
        path = models.get(row[1])
        if not path:
            continue
        for ext in (".mdx", ".mdl", ".MDX", ".MDL"):
            if path.endswith(ext):
                path = path[: -len(ext)] + ".m2"
        paths[row[0]] = path.replace("/", "\\")
    return paths


def catalog_models(catalog_file, sql_files):
    models = set()
    if catalog_file:
        for line in open(catalog_file, encoding="utf-8"):
            parts = line.split()
            if len(parts) >= 2:
                models.add(int(parts[1]))
    insert = re.compile(r"INSERT INTO `?dc_shapeshift_form_skins`?\s*(\([^)]*\))?\s*VALUES(.*?);", re.S | re.I)
    row = re.compile(r"\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,")
    for sql in sql_files or []:
        text = open(sql, encoding="utf-8").read()
        for match in insert.finditer(text):
            columns = match.group(1)
            if columns and [c.strip(" `") for c in columns.strip("()").split(",")][:3] != ["form", "race", "model"]:
                raise SystemExit(sql + ": unexpected column order " + columns)
            for values in row.finditer(match.group(2)):
                models.add(int(values.group(3)))
    return models


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--catalog")
    parser.add_argument("--sql", nargs="*")
    parser.add_argument("--dbc", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--keep-existing", action="store_true",
                        help="keep entries already in --out that the catalog no longer names")
    args = parser.parse_args()

    paths = model_paths(args.dbc)
    wanted = catalog_models(args.catalog, args.sql)
    if args.keep_existing:
        try:
            previous = open(args.out, encoding="utf-8").read()
        except FileNotFoundError:
            previous = ""
        for model, path in re.findall(r'\[(\d+)\] = "([^"]+)"', previous):
            if int(model) not in wanted:
                wanted.add(int(model))
                paths.setdefault(int(model), path.replace("\\\\", "\\"))
    missing = sorted(m for m in wanted if m not in paths)
    lines = [
        "-- AUTO-GENERATED by Custom/druids/generate_form_model_paths.py.",
        "-- Maps a shapeshift-form CreatureDisplayInfo id -> its M2 file path so",
        "-- UI/FormFrame.lua can Model:SetModel(path) it (SetDisplayInfo /",
        "-- SetCreature(displayId) do not reliably render on this 3.3.5a client).",
        "-- Re-run the generator after adding form skins; do not hand-edit.",
        "local DC = DCCollection or _G.DCCollection",
        "if not DC then return end",
        "",
        "DC.FormModelPaths = {",
    ]
    for model in sorted(m for m in wanted if m in paths):
        lines.append('    [%d] = "%s",' % (model, paths[model].replace("\\", "\\\\")))
    lines.append("}")
    with open(args.out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    print("%d entries written, %d display ids without a model: %s" % (len(wanted) - len(missing), len(missing), missing[:20]))


if __name__ == "__main__":
    main()
