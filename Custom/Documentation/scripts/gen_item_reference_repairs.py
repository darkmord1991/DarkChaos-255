#!/usr/bin/env python3
"""Emit Plaguelands/99_item_reference_repairs.sql -- the "Loading Items..." error block.

FIVE groups. The big one is NOT from the map-751 import at all.

1. 114 x "Item (Entry: N) does not have a correct display id (800xxx), must be 0."
   MISREAD THIS AT FIRST GLANCE AND IT LOOKS LIKE A MISSING DISPLAY. It is not.
   The core check is ObjectMgr.cpp:3534

       if (itemTemplate.DisplayInfoID != dbcitem->DisplayInfoID)

   i.e. item_template disagrees with **Item.dbc**, and the core then OVERWRITES
   item_template with the DBC value. "must be 0" means the DBC side reads 0.

   Where the 0 comes from: `item_dbc` is a runtime overlay merged OVER the binary
   Item.dbc at load, and 114 of its rows carry DisplayInfoID = 0 while both
   item_template AND the shipped Item.dbc carry the real 800xxx value. The overlay
   is the outlier, and because it wins, 114 DC custom items were being stripped of
   their icon at every boot.

   Checked before choosing a direction: all 114 exist in Item.dbc with a non-zero
   display, and every one of those displays exists in ItemDisplayInfo. Also checked:
   DisplayInfoID is the ONLY field that disagrees -- ClassID, SubclassID,
   Sound_Override_Subclassid, Material, InventoryType and SheatheType all match on
   every row. So the fix is a one-column sync, not a rebuild.

   PRE-EXISTING and unrelated to map 751 -- these are DC custom items in the
   52199-59520 range.

2. Four items with a PageText that does not exist. 3745 IS in cata_world and chains
   3745 -> 3746 -> 3747 -> 3748 -> 3749 -> 0, so the whole chain is imported for
   item 64666 (the schemas match exactly, 4 columns both sides). 3708, 3718 and 3722
   exist in NO source we have, so those three items get PageText = 0 -- the item
   keeps working, it just has no readable page.

3. Six items requiring reputation with faction 1168. That faction is Cataclysm's
   **Guild** reputation -- confirmed from the Cata client's own Faction.dbc, whose
   description reads "Guild reputation is your personal standing with your guild".
   3.3.5 has no guild reputation at all, so the requirement is unenforceable rather
   than merely missing: zeroed. The items are the Cata guild banners/standards.

4. Item 68647's spellid_1 96022 -- "Dousing Agent", present in the Cata client, so
   it goes into the 88_ spell downport rather than being zeroed. Handled there.

5. Bag family bit 15. Handled as a DBC row, NOT here -- see the note at the end.
"""
import os

ROOT = r"K:/Dark-Chaos/DarkChaos-255-Master/Custom"
OUT = os.path.join(ROOT, "Custom feature SQLs", "worlddb", "Plaguelands",
                   "99_item_reference_repairs.sql")
NL = chr(10)
BT = chr(96)

PAGE_CHAIN = [3745, 3746, 3747, 3748, 3749]
PAGE_DEAD = {60977: 3708, 62932: 3718, 63249: 3722}
GUILD_REP_ITEMS = [63359, 64398, 64399, 64400, 64401, 64402]


def bt(n):
    return BT + n + BT


def main():
    with open(OUT, "w", encoding="utf-8", newline=NL) as fh:
        w = fh.write
        w("-- 99_item_reference_repairs.sql -- item reference repairs, DB step 38." + NL + "--" + NL)
        w("-- GENERATED by Custom/Documentation/scripts/gen_item_reference_repairs.py." + NL + "--" + NL)
        w("-- ============================================================================" + NL)
        w("-- 1. 114 items losing their icon every boot -- the BIG one, and NOT from the" + NL)
        w("--    map-751 import. These are DC custom items, entries 52199-59520." + NL)
        w("--" + NL)
        w("--    The log line reads" + NL)
        w("--      Item (Entry: 52199) does not have a correct display id (800047), must be 0." + NL)
        w("--    which looks like a missing display. It is not. The core check is" + NL)
        w("--      ObjectMgr.cpp:3534  if (itemTemplate.DisplayInfoID != dbcitem->DisplayInfoID)" + NL)
        w("--    -- item_template disagreeing with **Item.dbc** -- and the core then" + NL)
        w("--    OVERWRITES item_template with the DBC value. \"must be 0\" = the DBC side" + NL)
        w("--    reads 0, so the icon is stripped at every startup." + NL)
        w("--" + NL)
        w("--    Where the 0 comes from: `item_dbc` is a runtime overlay merged OVER the" + NL)
        w("--    binary Item.dbc at load, and 114 of its rows carry DisplayInfoID = 0" + NL)
        w("--    while BOTH item_template and the shipped Item.dbc carry the real 800xxx" + NL)
        w("--    value. The overlay is the outlier and it wins." + NL)
        w("--" + NL)
        w("--    Verified before choosing a direction: all 114 exist in Item.dbc with a" + NL)
        w("--    non-zero display; every one of those displays exists in ItemDisplayInfo;" + NL)
        w("--    and DisplayInfoID is the ONLY column that disagrees -- ClassID," + NL)
        w("--    SubclassID, Sound_Override_Subclassid, Material, InventoryType and" + NL)
        w("--    SheatheType match on every row. Hence a one-column sync." + NL)
        w("-- ============================================================================" + NL + NL)
        w("UPDATE %s d" % bt("item_dbc") + NL)
        w("JOIN %s i ON i.%s = d.%s" % (bt("item_template"), bt("entry"), bt("ID")) + NL)
        w("SET d.%s = i.%s" % (bt("DisplayInfoID"), bt("displayid")) + NL)
        w("WHERE d.%s <> i.%s;" % (bt("DisplayInfoID"), bt("displayid")) + NL + NL)

        w("-- ---------------------------------------------------------------------------" + NL)
        w("-- 2. PageText" + NL)
        w("--    3745 exists in cata_world and chains 3745->3746->3747->3748->3749->0," + NL)
        w("--    so the whole chain comes across for item 64666. page_text has the same" + NL)
        w("--    four columns on both sides, so this is a straight copy." + NL)
        w("-- ---------------------------------------------------------------------------" + NL)
        ids = ",".join(str(x) for x in PAGE_CHAIN)
        w("DELETE FROM %s WHERE %s IN (%s);" % (bt("page_text"), bt("ID"), ids) + NL)
        w("INSERT INTO %s (%s, %s, %s, %s)" % (bt("page_text"), bt("ID"), bt("Text"),
                                               bt("NextPageID"), bt("VerifiedBuild")) + NL)
        w("SELECT %s, %s, %s, %s FROM %s.%s WHERE %s IN (%s);"
          % (bt("ID"), bt("Text"), bt("NextPageID"), bt("VerifiedBuild"),
             bt("cata_world"), bt("page_text"), bt("ID"), ids) + NL + NL)
        w("--    3708, 3718 and 3722 are in NO source we have -- not our page_text, not" + NL)
        w("--    cata_world. Nothing to import, so the reference is dropped: the item" + NL)
        w("--    keeps working, it just has no readable page." + NL)
        for e in sorted(PAGE_DEAD):
            w("UPDATE %s SET %s = 0 WHERE %s = %d AND %s = %d;"
              % (bt("item_template"), bt("PageText"), bt("entry"), e,
                 bt("PageText"), PAGE_DEAD[e]) + NL)
        w(NL)

        w("-- ---------------------------------------------------------------------------" + NL)
        w("-- 3. RequiredReputationFaction 1168 = Cataclysm's GUILD reputation" + NL)
        w("--    Confirmed from the Cata client's own Faction.dbc, whose description for" + NL)
        w("--    1168 reads \"Guild reputation is your personal standing with your guild\"." + NL)
        w("--    3.3.5 has no guild reputation, so this requirement is unenforceable, not" + NL)
        w("--    merely missing -- there is no rank a player could ever reach. Zeroed." + NL)
        w("--    (The six are the Cata guild banners: Banner of Cooperation, Standard of" + NL)
        w("--    Unity, Battle Standard of Coordination, x2 each.)" + NL)
        w("-- ---------------------------------------------------------------------------" + NL)
        w("UPDATE %s SET %s = 0, %s = 0" % (bt("item_template"),
                                            bt("RequiredReputationFaction"),
                                            bt("RequiredReputationRank")) + NL)
        w("WHERE %s IN (%s) AND %s = 1168;"
          % (bt("entry"), ",".join(str(x) for x in GUILD_REP_ITEMS),
             bt("RequiredReputationFaction")) + NL + NL)

        w("-- ---------------------------------------------------------------------------" + NL)
        w("-- 4. Item 68647 spellid_1 = 96022 -- NOT fixed here." + NL)
        w("--    96022 is \"Dousing Agent\" and IS present in the Cata 4.3.4 client, so it" + NL)
        w("--    is downported by 88_ (now 231 spells) rather than stripped. Re-apply 88_." + NL)
        w("--" + NL)
        w("-- 5. Bag family bit 15 -- NOT fixed here either, it is a DBC row." + NL)
        w("--    BagFamily 32768 = bit 15, and the core looks up ItemBagFamily id bit+1 =" + NL)
        w("--    16. Our ItemBagFamily has ids 0-15; Cata has 0-16. Rather than strip the" + NL)
        w("--    bit off the five items that carry it (Stag Eye, Severed Abomination Head," + NL)
        w("--    Giant Flesh-Eating Tadpole, Corpse Worm, Corpse-Fed Pike -- all cooking /" + NL)
        w("--    fishing ingredients), row 16 is added to ItemBagFamily from the Cata" + NL)
        w("--    client. That keeps the items' intent and also fixes 58949, which is" + NL)
        w("--    pre-existing. Note BagFamily 4096 = bit 12 -> id 13 is VALID and its 179" + NL)
        w("--    items were never in error." + NL)
        w("-- ---------------------------------------------------------------------------" + NL + NL)

        w("-- ---------------------------------------------------------------------------" + NL)
        w("-- Verification" + NL)
        w("-- ---------------------------------------------------------------------------" + NL)
        w("SELECT 'item_dbc rows still disagreeing on display (want 0)' AS what, COUNT(*) AS n" + NL)
        w("  FROM %s d JOIN %s i ON i.%s = d.%s WHERE d.%s <> i.%s"
          % (bt("item_dbc"), bt("item_template"), bt("entry"), bt("ID"),
             bt("DisplayInfoID"), bt("displayid")) + NL)
        w("UNION ALL SELECT 'page_text chain imported (want %d)', COUNT(*)" % len(PAGE_CHAIN) + NL)
        w("  FROM %s WHERE %s IN (%s)" % (bt("page_text"), bt("ID"), ids) + NL)
        w("UNION ALL SELECT 'items whose PageText points nowhere (want 0)', COUNT(*)" + NL)
        w("  FROM %s i WHERE i.%s > 0" % (bt("item_template"), bt("PageText")) + NL)
        w("    AND NOT EXISTS (SELECT 1 FROM %s p WHERE p.%s = i.%s)"
          % (bt("page_text"), bt("ID"), bt("PageText")) + NL)
        w("UNION ALL SELECT 'items still requiring faction 1168 (want 0)', COUNT(*)" + NL)
        w("  FROM %s WHERE %s = 1168;" % (bt("item_template"), bt("RequiredReputationFaction")) + NL + NL)
        w("-- must be empty: an item whose display, after the sync, is not in the shipped" + NL)
        w("-- ItemDisplayInfo overlay AND not zero" + NL)
        w("SELECT 'PROBLEM: synced display missing' AS problem, d.%s, d.%s"
          % (bt("ID"), bt("DisplayInfoID")) + NL)
        w("FROM %s d WHERE d.%s > 0" % (bt("item_dbc"), bt("DisplayInfoID")) + NL)
        w("  AND NOT EXISTS (SELECT 1 FROM %s x WHERE x.%s = d.%s)"
          % (bt("itemdisplayinfo_dbc"), bt("ID"), bt("DisplayInfoID")) + NL)
        w("  AND d.%s NOT BETWEEN 1 AND 799999;" % bt("DisplayInfoID") + NL)
    print("wrote %s" % OUT)
    print("  item_dbc display sync : 114 rows (one UPDATE ... JOIN)")
    print("  page_text imported    : %s" % PAGE_CHAIN)
    print("  PageText zeroed       : %s" % sorted(PAGE_DEAD))
    print("  guild-rep zeroed      : %s" % GUILD_REP_ITEMS)


main()
