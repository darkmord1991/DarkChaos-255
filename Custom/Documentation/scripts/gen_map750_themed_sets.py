#!/usr/bin/env python3
"""Generate `Custom/Custom feature SQLs/worlddb/HyjalCata/243_map750_zone_themed_sets.sql`.

Reads data/zone_themed_sets.csv (curated 2026-08-03: 75 items = 5 zones x 15
pieces; new_entry 400708-400782, each a stat-clone of a 400xxx ladder item with
a zone-flavored name and a Cata/newer displayid borrowed from the 60000-299999
downport corpus, slot/material verified).

Each item is cloned via the temporary-table trick so no column list is needed
(same pattern as 40_faction_starts.sql's spell/GO clones). Re-run after editing
the CSV rather than hand-editing the SQL.
"""

import csv
import io
import os

ZONE_DESC = {
    "4929": "Tidewatcher's regalia, issued to the coast wardens of Lor'danel.",
    "4930": "Bilgewater Cartel field kit. The cartel deducts losses from your pay.",
    "4931": "Skirmisher's gear from the contested groves of Ashenvale.",
    "4927": "Warden's vestments, sap-stained from the fight for Felwood.",
    "4926": "Stalker's furs, cured against Winterspring's endless frost.",
}

HEADER = """-- ---------------------------------------------------------------------------
-- 243  Map 750 -- zone-themed leveling sets (400708-400782)
-- ---------------------------------------------------------------------------
-- The 400xxx ladder is Hyjal-branded, which reads wrong dropping in Darkshore
-- or Winterspring. Five 15-piece THEMED sets fix that -- one per leveling
-- zone, stat-cloned from the zone's band-appropriate ladder tier (so power,
-- ItemLevel, Quality and the 238_-retuned RequiredLevel carry over verbatim)
-- with zone-flavored names and Cata/newer display ids from the downported
-- appearance corpus:
--
--   400708-400722  Tidewatcher's          Darkshore 4929     (tier-1 stats)
--   400723-400737  Bilgewater Profiteer's Azshara 4930       (tier-1 stats)
--   400738-400752  Ashenvale Skirmisher's Ashenvale 4931     (tier-2 stats)
--   400753-400767  Emerald Warden's       Felwood 4927       (tier-3 stats)
--   400768-400782  Frostsaber Stalker's   Winterspring 4926  (tier-3 stats)
--
-- Ladder ItemLevels (300/332/372) land every piece inside the item-upgrade
-- system's tier-4 window (300-411) -> token-upgradeable out of the box (see
-- 244_). 237_ wires these into the per-zone drop references; Hyjal itself
-- keeps the original epic ladder (already Hyjal-themed).
--
-- Slot note: the ladder tiers are NOT slot-parallel -- tier 1 = wrist/waist/
-- hands, tier 2 = feet/shoulder/legs, tier 3 = wrist/hands/waist. Each set
-- clones its own tier's layout, so slot coverage varies by zone on purpose;
-- the re-banded native Cata drops (236_) fill the remaining slots.
--
-- Generated by Custom/Documentation/scripts/gen_map750_themed_sets.py from
-- data/zone_themed_sets.csv -- edit the CSV and re-run, never this file.
-- Run AFTER 238_ (RequiredLevel retune must be baked in before cloning).
-- Idempotent (DELETE + re-clone).
-- ---------------------------------------------------------------------------

DELETE FROM `item_template` WHERE `entry` BETWEEN 400708 AND 400782;
"""


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.abspath(os.path.join(here, "..", ".."))
    src = os.path.join(here, "data", "zone_themed_sets.csv")
    out = os.path.join(repo, "Custom feature SQLs", "worlddb", "HyjalCata",
                       "243_map750_zone_themed_sets.sql")

    rows = list(csv.DictReader(io.open(src, encoding="utf-8")))
    assert len(rows) == 75, f"expected 75 rows, got {len(rows)}"
    entries = [int(r["new_entry"]) for r in rows]
    assert len(set(entries)) == 75 and min(entries) == 400708 and max(entries) == 400782

    parts = [HEADER]
    for r in rows:
        zone_id = r["zone"].split("(")[1].rstrip(")")
        name = r["new_name"].replace("'", "''")
        desc = ZONE_DESC[zone_id].replace("'", "''")
        parts.append(
            "\nDROP TEMPORARY TABLE IF EXISTS `tmp_dc750_item`;\n"
            "CREATE TEMPORARY TABLE `tmp_dc750_item` AS\n"
            f"SELECT * FROM `item_template` WHERE `entry` = {r['clone_from']};\n"
            f"UPDATE `tmp_dc750_item` SET `entry` = {r['new_entry']}, `name` = '{name}',\n"
            f"    `displayid` = {r['displayid']}, `description` = '{desc}';\n"
            "INSERT INTO `item_template` SELECT * FROM `tmp_dc750_item`;\n"
        )
    parts.append(
        "\nDROP TEMPORARY TABLE IF EXISTS `tmp_dc750_item`;\n"
        "\n-- ---------------------------------------------------------------------------\n"
        "-- Trailer -- verification (expect 75 rows, displayid > 0, ilvl 300/332/372)\n"
        "-- ---------------------------------------------------------------------------\n"
        "-- SELECT COUNT(*), MIN(ItemLevel), MAX(ItemLevel) FROM item_template\n"
        "-- WHERE entry BETWEEN 400708 AND 400782;\n"
        "-- SELECT entry, name, displayid, RequiredLevel FROM item_template\n"
        "-- WHERE entry BETWEEN 400708 AND 400782 ORDER BY entry;\n"
    )

    io.open(out, "w", encoding="utf-8", newline="\n").write("".join(parts))
    print(f"wrote {out} ({len(rows)} items)")


if __name__ == "__main__":
    main()
