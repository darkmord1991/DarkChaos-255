#!/usr/bin/env python3
"""Emit 100_missing_summon_creatures.sql and 102_wander_restore.sql.

100_ -- THE SPELL -> CREATURE DEPENDENCY, one level deeper than the item -> spell one.
    Creature::Create(): creature template (guidlow: 2474, entry: 50374) does not exist.
    Auras: unknown creature id = 50380 ... From Spell Aura Transform in Spell ID = 93460
Neither creature is spawned anywhere, summoned by any SmartAI action, listed in
creature_summon_groups, or used as a vehicle accessory -- they are summoned BY THE SPELLS
88_ downported. A spell can carry a creature id in EffectMiscValue for
SPELL_EFFECT_SUMMON (28) / SUMMON_PET (56) / TRANS_DOOR (90) / SUMMON_OBJECT (112) and for
SPELL_AURA_TRANSFORM (aura 56, which needs the creature only for its modelid).

Auditing spell_dbc for every such reference found **75 missing creature ids, 68 of them
available in cata_world, 66 of those referenced by a spell 88_ added.** This file imports
those 66 -- the same recipe as 89_, at PLAIN Cata ids because that is the id the spell
effect names; the +4,100,000 band is for spawned content and a summon effect cannot be
remapped without editing the spell.

The 7 with no cata_world row (and 2 more referenced only by pre-existing spells) are left
alone and listed at the end of this file rather than faked.

102_ -- SILVERPINE (AND THE REST OF 751) BARELY WANDERS.
Measured rather than assumed: Silverpine on 751 has 591 wandering spawns out of 4,026 --
and `cata_world` has *exactly* the same 591, so the import was faithful. But Tirisfal on
the same map runs 48% wandering against Silverpine's 15%, and cata_world is a known
MovementType-stripped source. Cross-checking every static 751 spawn against nelt_world by
creature ENTRY finds **3,068 spawns (1,502 of them in Silverpine) whose entry demonstrably
wanders in nelt but is pinned here.**

Restored conservatively -- a spawn is only touched when ALL of:
  * it is currently MovementType 0 with no wander distance
  * its base entry wanders in nelt_world with spawndist > 0
  * it is NOT in a creature_formation (moving a member breaks the formation)
  * it has NO waypoint path of its own (creature_addon.path_id) and no SmartAI
    waypoint script, so nothing scripted is overridden
wander_distance takes nelt's median for that entry, clamped to a sane 3..15.
"""
import os

ROOT = r"K:/Dark-Chaos/DarkChaos-255-Master/Custom"
OUTDIR = os.path.join(ROOT, "Custom feature SQLs", "worlddb", "Plaguelands")
NL = chr(10)
BT = chr(96)


def bt(n):
    return BT + n + BT


SUMMON_SRC = """(
  SELECT `ID` s, `EffectMiscValue_1` cre FROM {sd} WHERE `EffectMiscValue_1`>0 AND (`Effect_1` IN (28,56,90,112) OR `EffectAura_1`=56)
  UNION ALL SELECT `ID`, `EffectMiscValue_2` FROM {sd} WHERE `EffectMiscValue_2`>0 AND (`Effect_2` IN (28,56,90,112) OR `EffectAura_2`=56)
  UNION ALL SELECT `ID`, `EffectMiscValue_3` FROM {sd} WHERE `EffectMiscValue_3`>0 AND (`Effect_3` IN (28,56,90,112) OR `EffectAura_3`=56)
)""".format(sd=bt("spell_dbc"))


def write_100():
    p = os.path.join(OUTDIR, "100_missing_summon_creatures.sql")
    with open(p, "w", encoding="utf-8", newline=NL) as fh:
        w = fh.write
        w("-- 100_missing_summon_creatures.sql -- map 751 extension, DB step 39." + NL + "--" + NL)
        w("-- GENERATED by Custom/Documentation/scripts/gen_summon_and_wander_repairs.py." + NL + "--" + NL)
        w("-- THE SPELL -> CREATURE DEPENDENCY. One level deeper than the item -> spell one" + NL)
        w("-- 94_/88_ already dealt with, and it fires at RUNTIME, not at boot:" + NL)
        w("--   Creature::Create(): creature template (guidlow: 2474, entry: 50374) does not exist." + NL)
        w("--   Auras: unknown creature id = 50380 ... From Spell Aura Transform in Spell ID = 93460" + NL)
        w("--" + NL)
        w("-- Neither creature is spawned anywhere, summoned by a SmartAI action, listed in" + NL)
        w("-- creature_summon_groups, or used as a vehicle accessory -- checked all four." + NL)
        w("-- They are summoned BY THE SPELLS 88_ downported: a spell carries the creature id" + NL)
        w("-- in EffectMiscValue for SPELL_EFFECT_SUMMON (28) / SUMMON_PET (56) /" + NL)
        w("-- TRANS_DOOR (90) / SUMMON_OBJECT (112), and for SPELL_AURA_TRANSFORM (aura 56," + NL)
        w("-- which needs the creature only for its modelid -- hence the \"only need its" + NL)
        w("-- modelid\" wording in that log line)." + NL)
        w("--" + NL)
        w("-- Auditing spell_dbc for every such reference: 75 missing creature ids, 68 of them" + NL)
        w("-- in cata_world, 66 of those named by a spell 88_ added. Those 66 are imported here" + NL)
        w("-- at PLAIN Cata ids -- that is the id the spell effect names, and unlike spawned" + NL)
        w("-- content a summon target cannot be moved to the +4,100,000 band without editing" + NL)
        w("-- the spell itself." + NL)
        w("--" + NL)
        w("-- Anything with no cata_world row is NOT faked; the tail of this file lists what" + NL)
        w("-- is still unresolved so it stays visible." + NL + NL)

        # -------- creature_template --------
        w("-- ---------------------------------------------------------------------------" + NL)
        w("-- 1. creature_template -- copied from cata_world, columns named explicitly." + NL)
        w("--    A `SELECT *` cannot be used: the two schemas differ (creature_template" + NL)
        w("--    drift is documented), so only the columns both sides share are copied and" + NL)
        w("--    the rest take our defaults." + NL)
        w("-- ---------------------------------------------------------------------------" + NL)
        w("-- A REGULAR scratch table, not TEMPORARY, and not by accident: MySQL cannot" + NL)
        w("-- reference a TEMPORARY table more than once in one query (error 1137," + NL)
        w("-- \"Can't reopen table\"), and the verification UNION below reads it three" + NL)
        w("-- times. It is dropped again at the end of this file." + NL)
        w("--" + NL)
        w("-- A snapshot table is REQUIRED here rather than repeating the sub-select: the" + NL)
        w("-- predicate is \"not yet in creature_template\", which the INSERT below makes" + NL)
        w("-- false. Recomputing it afterwards would return an empty set and the" + NL)
        w("-- verification would silently report zero of everything." + NL)
        w("DROP TABLE IF EXISTS `_dc_missing_summons`;" + NL)
        w("CREATE TABLE `_dc_missing_summons` (`entry` INT PRIMARY KEY) ENGINE=InnoDB;" + NL)
        w("INSERT INTO `_dc_missing_summons` (`entry`)" + NL)
        w("SELECT DISTINCT z.cre FROM " + SUMMON_SRC + " z" + NL)
        w("WHERE z.s >= 70956" + NL)
        w("  AND NOT EXISTS (SELECT 1 FROM %s t WHERE t.%s = z.cre)" % (bt("creature_template"), bt("entry")) + NL)
        w("  AND EXISTS (SELECT 1 FROM %s.%s c WHERE c.%s = z.cre);"
          % (bt("cata_world"), bt("creature_template"), bt("entry")) + NL + NL)

        w("INSERT INTO %s" % bt("creature_template") + NL)
        w("  (%s)" % ", ".join(bt(c) for c in COLS) + NL)
        w("SELECT %s" % ", ".join(SEL[c] for c in COLS) + NL)
        w("FROM %s.%s c JOIN `_dc_missing_summons` m ON m.`entry` = c.%s"
          % (bt("cata_world"), bt("creature_template"), bt("entry")) + NL)
        w("WHERE NOT EXISTS (SELECT 1 FROM %s t WHERE t.%s = c.%s);"
          % (bt("creature_template"), bt("entry"), bt("entry")) + NL + NL)

        # -------- model / addon --------
        w("-- ---------------------------------------------------------------------------" + NL)
        w("-- 2. creature_template_model -- the display layer. Without it the creature" + NL)
        w("--    loads but renders as nothing (see the three-layer display rule)." + NL)
        w("-- ---------------------------------------------------------------------------" + NL)
        w("INSERT INTO %s (%s, %s, %s, %s, %s)"
          % (bt("creature_template_model"), bt("CreatureID"), bt("Idx"),
             bt("CreatureDisplayID"), bt("DisplayScale"), bt("Probability")) + NL)
        w("SELECT m.`entry`, 0, c.%s, 1, 1 FROM %s.%s c JOIN `_dc_missing_summons` m ON m.`entry`=c.%s"
          % (bt("modelid1"), bt("cata_world"), bt("creature_template"), bt("entry")) + NL)
        w("WHERE c.%s > 0" % bt("modelid1") + NL)
        w("  AND NOT EXISTS (SELECT 1 FROM %s x WHERE x.%s = m.`entry` AND x.%s = 0);"
          % (bt("creature_template_model"), bt("CreatureID"), bt("Idx")) + NL + NL)
        w("-- must be paired with a CreatureDisplayInfo row or the model id resolves to" + NL)
        w("-- nothing; the verification block below reports any that are not covered." + NL + NL)

        # -------- verification --------
        w("-- ---------------------------------------------------------------------------" + NL)
        w("-- Verification" + NL)
        w("-- ---------------------------------------------------------------------------" + NL)
        w("SELECT 'summon targets imported' AS what, COUNT(*) AS n FROM `_dc_missing_summons`" + NL)
        w("UNION ALL SELECT '  ...now present in creature_template (want the same)', COUNT(*)" + NL)
        w("  FROM `_dc_missing_summons` m JOIN %s t ON t.%s = m.`entry`"
          % (bt("creature_template"), bt("entry")) + NL)
        w("UNION ALL SELECT '  ...with a display model row', COUNT(*)" + NL)
        w("  FROM `_dc_missing_summons` m JOIN %s x ON x.%s = m.`entry`"
          % (bt("creature_template_model"), bt("CreatureID")) + NL)
        w("UNION ALL SELECT 'spell summon/transform targets STILL missing', COUNT(DISTINCT z.cre)" + NL)
        w("  FROM " + SUMMON_SRC + " z" + NL)
        w("  WHERE NOT EXISTS (SELECT 1 FROM %s t WHERE t.%s = z.cre);"
          % (bt("creature_template"), bt("entry")) + NL + NL)

        w("-- what is left, and why -- these have NO cata_world row to copy, so they are" + NL)
        w("-- reported rather than invented. Expect a handful; they belong to spells that" + NL)
        w("-- were already present before 88_." + NL)
        w("SELECT 'UNRESOLVED: no source for this summon target' AS problem," + NL)
        w("       z.cre AS creature, GROUP_CONCAT(DISTINCT z.s ORDER BY z.s) AS from_spells" + NL)
        w("FROM " + SUMMON_SRC + " z" + NL)
        w("WHERE NOT EXISTS (SELECT 1 FROM %s t WHERE t.%s = z.cre)" % (bt("creature_template"), bt("entry")) + NL)
        w("GROUP BY z.cre ORDER BY z.cre;" + NL + NL)
        w("-- ---------------------------------------------------------------------------" + NL)
        w("-- DISPLAY COVERAGE -- READ BEFORE CALLING THIS DONE" + NL)
        w("-- Importing the template stops \"creature template does not exist\" and stops the" + NL)
        w("-- transform aura complaining. It does NOT make the summon VISIBLE. A creature" + NL)
        w("-- needs three layers: creature_template_model (written above), creature_model_info," + NL)
        w("-- and a CreatureDisplayInfo row in the DBC." + NL)
        w("--" + NL)
        w("-- Only 5 of the 66 models appear in the `creaturedisplayinfo_dbc` overlay -- and" + NL)
        w("-- that overlay is an AUDIT source, not the authority: the server reads its binary" + NL)
        w("-- data/dbc/CreatureDisplayInfo.dbc, proven for this exact table on 2026-08-02." + NL)
        w("-- So the query below is a LOWER BOUND on what still needs display work; check the" + NL)
        w("-- shipped DBC for the real answer. Expect a display pass to follow, as after every" + NL)
        w("-- previous creature import." + NL)
        w("-- ---------------------------------------------------------------------------" + NL)
        w("SELECT 'imported summon with no display row in the overlay' AS problem," + NL)
        w("       m.`entry`, x.`CreatureDisplayID`" + NL)
        w("FROM `_dc_missing_summons` m" + NL)
        w("JOIN `creature_template_model` x ON x.`CreatureID` = m.`entry`" + NL)
        w("WHERE NOT EXISTS (SELECT 1 FROM `creaturedisplayinfo_dbc` d WHERE d.`ID` = x.`CreatureDisplayID`)" + NL)
        w("ORDER BY m.`entry`;" + NL + NL)
        w("DROP TABLE IF EXISTS `_dc_missing_summons`;" + NL)
    print("wrote %s" % p)


# columns copied from cata_world.creature_template -> ours (shared names only)
# The columns creature_template SHARES between acore_world and cata_world, derived from
# INFORMATION_SCHEMA rather than guessed -- the first attempt hardcoded `scale` (absent
# from ours) and `InhabitType` (absent from BOTH), which is exactly the drift the
# creature_template notes warn about. Everything not listed takes our own default.
# AIName / ScriptName are deliberately EXCLUDED: importing a Cata script name that this
# core does not register makes the creature fail to load rather than merely misbehave.
COLS = ["entry", "name", "subname", "minlevel", "maxlevel", "faction", "npcflag",
        "speed_walk", "speed_run", "rank", "dmgschool", "BaseAttackTime", "RangeAttackTime",
        "unit_class", "unit_flags", "unit_flags2", "family", "type", "type_flags",
        "MovementType", "HoverHeight", "RegenHealth", "flags_extra"]
SEL = {c: "c." + bt(c) for c in COLS}
SEL["name"] = "CONVERT(c." + bt("name") + " USING utf8mb4) COLLATE utf8mb4_general_ci"
SEL["subname"] = "CONVERT(c." + bt("subname") + " USING utf8mb4) COLLATE utf8mb4_general_ci"


def write_102():
    p = os.path.join(OUTDIR, "102_wander_restore.sql")
    BASE = ("(CASE WHEN c.%s >= 4100000 THEN c.%s - 4100000"
            " WHEN c.%s >= 3600000 THEN c.%s - 3600000 ELSE c.%s END)"
            % (bt("id"), bt("id"), bt("id"), bt("id"), bt("id")))
    with open(p, "w", encoding="utf-8", newline=NL) as fh:
        w = fh.write
        w("-- 102_wander_restore.sql -- map 751 extension, DB step 40." + NL + "--" + NL)
        w("-- GENERATED by Custom/Documentation/scripts/gen_summon_and_wander_repairs.py." + NL + "--" + NL)
        w("-- \"Silverpine Forest spawns seem pretty static, no wandering waypoints mostly\"." + NL)
        w("--" + NL)
        w("-- MEASURED, NOT ASSUMED, AND THE FIRST ANSWER WAS THAT NOTHING IS WRONG:" + NL)
        w("-- Silverpine on 751 has 591 wandering spawns out of 4,026, and `cata_world` has" + NL)
        w("-- EXACTLY the same 591 -- so the import copied its source faithfully." + NL)
        w("--" + NL)
        w("-- What gave it away was the neighbour: Tirisfal on the same map runs 48%" + NL)
        w("-- wandering against Silverpine's 15%. cata_world is a KNOWN MovementType-stripped" + NL)
        w("-- source, so the source itself is the defect. Cross-checking every static 751" + NL)
        w("-- spawn against nelt_world by creature ENTRY finds 3,068 spawns -- 1,502 of them" + NL)
        w("-- in Silverpine -- whose entry demonstrably wanders in nelt but is pinned here." + NL)
        w("--" + NL)
        w("-- CONSERVATIVE BY CONSTRUCTION. A spawn is touched only when ALL hold:" + NL)
        w("--   * currently MovementType 0 AND wander_distance 0" + NL)
        w("--   * its base entry wanders in nelt_world with spawndist > 0" + NL)
        w("--   * it is NOT in a creature_formation -- moving one member breaks the group" + NL)
        w("--   * it has no waypoint path of its own (creature_addon.path_id) and no" + NL)
        w("--     SmartAI waypoint script, so nothing scripted is overridden" + NL)
        w("-- wander_distance takes nelt's median spawndist for that entry, clamped 3..15 so" + NL)
        w("-- one odd source value cannot send a mob wandering across the zone." + NL + NL)

        w("UPDATE %s c" % bt("creature") + NL)
        w("JOIN (" + NL)
        w("    SELECT n.%s AS id," % bt("id") + NL)
        w("           LEAST(15, GREATEST(3, ROUND(AVG(n.%s)))) AS dist" % bt("spawndist") + NL)
        w("    FROM %s.%s n" % (bt("nelt_world"), bt("creature")) + NL)
        w("    WHERE n.%s = 1 AND n.%s > 0" % (bt("MovementType"), bt("spawndist")) + NL)
        w("    GROUP BY n.%s" % bt("id") + NL)
        w(") w ON w.`id` = " + BASE + NL)
        w("SET c.%s = 1, c.%s = w.`dist`" % (bt("MovementType"), bt("wander_distance")) + NL)
        w("WHERE c.%s = 751" % bt("map") + NL)
        w("  AND c.%s = 0 AND c.%s = 0" % (bt("MovementType"), bt("wander_distance")) + NL)
        w("  AND NOT EXISTS (SELECT 1 FROM %s f WHERE f.%s = c.%s)"
          % (bt("creature_formations"), bt("memberGUID"), bt("guid")) + NL)
        w("  AND NOT EXISTS (SELECT 1 FROM %s a WHERE a.%s = c.%s AND a.%s > 0)"
          % (bt("creature_addon"), bt("guid"), bt("guid"), bt("path_id")) + NL)
        w("  AND NOT EXISTS (SELECT 1 FROM %s s WHERE s.%s = 0" % (bt("smart_scripts"), bt("source_type")) + NL)
        w("                    AND s.%s = c.%s AND s.%s IN (53, 54));"
          % (bt("entryorguid"), bt("id"), bt("action_type")) + NL + NL)

        w("-- ---------------------------------------------------------------------------" + NL)
        w("-- Verification" + NL)
        w("-- ---------------------------------------------------------------------------" + NL)
        w("SELECT 'map-751 spawns now wandering' AS what, COUNT(*) AS n" + NL)
        w("  FROM %s WHERE %s = 751 AND %s = 1" % (bt("creature"), bt("map"), bt("MovementType")) + NL)
        w("UNION ALL SELECT '  ...in Silverpine', COUNT(*) FROM %s" % bt("creature") + NL)
        w("  WHERE %s = 751 AND %s = 1" % (bt("map"), bt("MovementType")) + NL)
        w("    AND %s BETWEEN -750 AND 3450 AND %s BETWEEN -1133 AND 1667"
          % (bt("position_y"), bt("position_x")) + NL)
        w("UNION ALL SELECT 'formation members accidentally set wandering (want 0)', COUNT(*)" + NL)
        w("  FROM %s c JOIN %s f ON f.%s = c.%s"
          % (bt("creature"), bt("creature_formations"), bt("memberGUID"), bt("guid")) + NL)
        w("  WHERE c.%s = 751 AND c.%s = 1" % (bt("map"), bt("MovementType")) + NL)
        w("UNION ALL SELECT 'waypoint spawns accidentally set wandering (want 0)', COUNT(*)" + NL)
        w("  FROM %s c JOIN %s a ON a.%s = c.%s AND a.%s > 0"
          % (bt("creature"), bt("creature_addon"), bt("guid"), bt("guid"), bt("path_id")) + NL)
        w("  WHERE c.%s = 751 AND c.%s = 1;" % (bt("map"), bt("MovementType")) + NL)
    print("wrote %s" % p)


write_100()
write_102()
