#!/usr/bin/env python3
"""Generate `Custom/Level Areas/Cata Hyjal 80-130/10_faction_bases.sql`.

Placement rules learned the hard way on map 750:

* Anchor on a coordinate whose in-game `.gps` reports **GroundZ == FloorZ**.  When the
  two differ there is a VMAP object above the terrain at that spot, and anything placed
  there either stands on the object or clips inside it.
* Keep the rings SMALL.  Terrain around the Grove of Aessina shelf is flat to within
  ~0.6 yd out to ~13 yd, but climbs to 1210.8 by 20 yd to the west -- an 18 yd ring put
  half the town on a slope, floating.
* Never anchor on arbitrary creatures.  Hyjal Bear Cubs sit *in* Climbing Trees, so
  their z is tree height; service NPCs are always ground-placed and make good references.

Each camp's `z` should be the measured ground height at its centre, NOT a nearby
creature's z and NOT the player's z while flying.

Re-run after editing CAMPS to re-emit the SQL.
"""

import io
import math
import os

# --------------------------------------------------------------------------------------
# Camp definitions.  cx/cy/cz must come from a verified GroundZ == FloorZ reading.
# --------------------------------------------------------------------------------------
CAMPS = [
    dict(
        key="A",
        name="Jaina's Encampment",
        # Verified in-game: X 4443.50  Y -2077.47  Z 1206.18, GroundZ == FloorZ == 1206.1843.
        # Real neighbours within 13 yd read 1206.05-1206.67, so the shelf is flat here.
        cx=4443.50, cy=-2077.47, cz=1206.25,
        guid0=9020000,
        service_radius=13.0,
        guard_radius=16.0,
        note="Grove of Aessina shelf",
        ring=[
            (830023, "Innkeeper Cerelina"),
            (830024, "Emberwood Sap Quartermaster"),
            (830135, "Encampment Banker"),
            (830136, "Encampment Auctioneer"),
            (830137, "Encampment Provisioner"),
            (830138, "Encampment Trader"),
            (830139, "Encampment Cook"),
            (830140, "Encampment Alchemist"),
            (830141, "Encampment Weaponsmith"),
            (830142, "Encampment Armorer"),
            (830143, "Encampment Stable Master"),
            (830144, "Encampment Tabard Vendor"),
        ],
        guards=[(830021, "Encampment Guard")] * 3 + [(830161, "Hyjal Frontier Soldier")] * 3,
    ),
    dict(
        key="H",
        name="Thrall's Vanguard",
        # PENDING a verified GroundZ == FloorZ reading -- see the README. The scouted area
        # (5660.58, -2980.15) reported GroundZ 1546.50 but FloorZ 1560.70, i.e. a VMAP
        # object 14 yd above the terrain, so neither height is safe to build on blind.
        cx=None, cy=None, cz=None,
        guid0=9020030,
        service_radius=13.0,
        guard_radius=16.0,
        note="PENDING verified ground coordinate",
        ring=[
            (830146, "Innkeeper Garruka"),
            (830147, "Emberwood Sap Quartermaster"),
            (830148, "Vanguard Banker"),
            (830149, "Vanguard Auctioneer"),
            (830150, "Vanguard Provisioner"),
            (830151, "Vanguard Trader"),
            (830152, "Vanguard Cook"),
            (830153, "Vanguard Shaman Supplier"),
            (830154, "Vanguard Weaponsmith"),
            (830155, "Vanguard Armorer"),
            (830156, "Vanguard Stable Master"),
            (830157, "Vanguard Tabard Vendor"),
        ],
        guards=[(830022, "Vanguard Grunt")] * 3 + [(830162, "Hyjal Vanguard Warrior")] * 3,
    ),
]

HEADER = """-- ---------------------------------------------------------------------------
-- 10  Faction bases: Jaina's Encampment (Alliance) + Thrall's Vanguard (Horde)
-- ---------------------------------------------------------------------------
-- Map 750 has NO Alliance or Horde presence -- every NPC on it is neutral
-- (Guardians of Hyjal 2252 / 2233, or 35). Zero faction-12 and zero faction-29
-- creatures, so neither side has a base, an innkeeper to bind at, or a
-- quartermaster of its own.
--
-- The rosters already exist as `creature_template` rows WITH complete vendor
-- stock (288 npc_vendor lines across 16 vendors, 0 missing items, 0 missing
-- ItemExtendedCost rows). They were authored for the superseded map 1410 and
-- never placed. This file re-homes them; nothing is re-authored.
--
-- PLACEMENT (revised after in-game testing -- the first pass floated):
--   * Centres come from a verified `.gps` reading where **GroundZ == FloorZ**.
--     Where those two differ there is a VMAP object above the terrain and
--     anything placed there stands on the object or clips into it.
--   * Rings are deliberately tight. The Grove of Aessina shelf is flat to
--     within ~0.6 yd out to ~13 yd but climbs to 1210.8 by 20 yd westward, so
--     the original 18 yd ring ran half the town onto a slope.
--
-- Generated by Custom/Documentation/scripts/gen_hyjal_camps.py -- edit the CAMPS
-- table there and re-run rather than hand-editing this file.
--
-- GUID sub-block 9020000-9020047 (the wider 9020000-9020499 reservation is
-- shared with 41_start_services.sql and 42_graveyards_curated.sql -- the
-- DELETE below is scoped so re-running this file cannot wipe theirs).
-- Idempotent.
-- ---------------------------------------------------------------------------

-- 1. Retire the map-1410 placements (that map is superseded).
DELETE FROM `creature` WHERE `id` BETWEEN 830000 AND 830999 AND `map` = 1410;

-- 2. Place the camps on map 750.
DELETE FROM `creature` WHERE `guid` BETWEEN 9020000 AND 9020047;
INSERT INTO `creature` (`guid`, `id`, `map`, `zoneId`, `areaId`, `spawnMask`, `phaseMask`,
    `equipment_id`, `position_x`, `position_y`, `position_z`, `orientation`, `spawntimesecs`,
    `wander_distance`, `currentwaypoint`, `curhealth`, `curmana`, `MovementType`, `npcflag`,
    `unit_flags`, `dynamicflags`, `ScriptName`, `VerifiedBuild`, `CreateObject`, `Comment`) VALUES
"""


def build_rows():
    rows, pending = [], []
    for camp in CAMPS:
        if camp["cx"] is None:
            pending.append(camp)
            continue
        guid = camp["guid0"]
        count = len(camp["ring"])
        for index, (entry, label) in enumerate(camp["ring"]):
            angle = 2 * math.pi * index / count
            rows.append((
                guid, entry,
                camp["cx"] + camp["service_radius"] * math.cos(angle),
                camp["cy"] + camp["service_radius"] * math.sin(angle),
                camp["cz"],
                (angle + math.pi) % (2 * math.pi),      # face the camp centre
                f"{camp['name']} - {label}",
            ))
            guid += 1
        count = len(camp["guards"])
        for index, (entry, label) in enumerate(camp["guards"]):
            angle = 2 * math.pi * index / count + math.pi / count
            rows.append((
                guid, entry,
                camp["cx"] + camp["guard_radius"] * math.cos(angle),
                camp["cy"] + camp["guard_radius"] * math.sin(angle),
                camp["cz"],
                angle % (2 * math.pi),                   # guards face outward
                f"{camp['name']} - {label}",
            ))
            guid += 1
    return rows, pending


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.abspath(os.path.join(here, "..", ".."))
    out = os.path.join(repo, "Level Areas", "Cata Hyjal 80-130", "10_faction_bases.sql")

    rows, pending = build_rows()
    values = ",\n".join(
        "({}, {}, 750, 4923, 4923, 1, 1, 0, {:.3f}, {:.3f}, {:.3f}, {:.3f}, 300, 0, 0, 0, 0, 0, "
        "0, 0, 0, '', NULL, 0, '{}')".format(g, e, x, y, z, o, c.replace("'", "''"))
        for g, e, x, y, z, o, c in rows
    )

    body = HEADER + values + ";\n"
    if pending:
        body += "\n-- PENDING, not emitted (no verified GroundZ == FloorZ coordinate yet):\n"
        for camp in pending:
            body += f"--   {camp['name']} -- guids {camp['guid0']}+, {camp['note']}\n"

    io.open(out, "w", encoding="utf-8", newline="\n").write(body)
    print(f"wrote {out} ({len(rows)} spawns)")
    for camp in CAMPS:
        state = "PENDING" if camp["cx"] is None else \
            f"({camp['cx']}, {camp['cy']}, {camp['cz']})"
        print(f"  {camp['name']:<22} {state}")


if __name__ == "__main__":
    main()
