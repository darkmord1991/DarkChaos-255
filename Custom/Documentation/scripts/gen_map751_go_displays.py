#!/usr/bin/env python3
"""Downport the 18 GameObjectDisplayInfo rows map 751's gameobjects reference and
3.3.5 does not have, and write all three halves of the fix.

THE SYMPTOM
    Gameobject (GUID: ... Entry 4808816 GoType: 3) has an invalid displayId (10615),
    not loaded.
146 spawns over 49 gameobject entries on map 751 never load at all. Nothing on any
other map uses these 18 displays, so the change cannot touch existing content.

LAYOUT: OURS IS CATA'S FIRST 19 FIELDS
Cata 4.3.4's GameObjectDisplayInfo.dbc is 21 fields / 84 bytes; ours is 19 / 76. The
extra two are Cata additions and are dropped. Verified rather than assumed, over 150
ids present in both clients: fields 0-11 (ID, ModelName, Sound[10]) and field 18
(ObjectEffectPackageID) agree 100%. Only 12-17, the GeoBox floats, differ, on ~10% of
rows -- Blizzard recalculating bounding boxes between expansions, not a misalignment.
A layout error would fail ~100% on specific fields. New rows take Cata's GeoBox
because there is no stock value to preserve.

NO MODEL WORK IS NEEDED. All 18 referenced models -- including the Cata-only
expansion03 worgen and deepholm doodads -- are already in the live client, put there
by earlier downport passes. Checked by probing every live archive for each path, both
as .mdx and as .m2.

EMITS THREE THINGS, because a display id has to exist in all three places:
  * Plaguelands/97_gameobject_displays.sql -- the gameobjectdisplayinfo_dbc overlay
  * Custom/CSV DBC/GameObjectDisplayInfo.csv  -- the source of truth for rebuilds
  * Custom/DBCs/GameObjectDisplayInfo.dbc     -- appended in place, originals untouched
The SERVER's binary DBC is what gates whether a spawn loads (see
custom-dbcs-blanket-rebuild-is-destructive / the CreatureDisplayInfo proof), so the
rebuilt .dbc must reach data/dbc as well as the client patches.
"""
import os, struct, csv, io

ROOT = "K:/Dark-Chaos/DarkChaos-255-Master/Custom/"
OUT_SQL = ROOT + "Custom feature SQLs/worlddb/Plaguelands/97_gameobject_displays.sql"
CSV_PATH = ROOT + "CSV DBC/GameObjectDisplayInfo.csv"
DBC_PATH = ROOT + "DBCs/GameObjectDisplayInfo.dbc"
NL = chr(10)
BT = chr(96)
BS = chr(92)

MISSING = [9140, 9141, 9146, 9342, 9374, 9375, 9376, 9539, 9667,
           9883, 9943, 10014, 10216, 10237, 10238, 10241, 10414, 10615]

COLS = ["ID", "ModelName", "Sound_1", "Sound_2", "Sound_3", "Sound_4", "Sound_5",
        "Sound_6", "Sound_7", "Sound_8", "Sound_9", "Sound_10", "GeoBoxMinX",
        "GeoBoxMinY", "GeoBoxMinZ", "GeoBoxMaxX", "GeoBoxMaxY", "GeoBoxMaxZ",
        "ObjectEffectPackageID"]
FLOATS = set(range(12, 18))
STRINGS = {1}


def bt(n):
    return BT + n + BT


def load_cata():
    scripts = os.path.dirname(os.path.abspath(__file__))
    src = open(os.path.join(scripts, "gen_map751_item_template.py"),
               encoding="utf-8").read().split("def main()")[0]
    ns = {"__file__": os.path.join(scripts, "gen_map751_item_template.py"), "__name__": "g"}
    exec(compile(src, "gen", "exec"), ns)
    d = ns["read_client"]("DBFilesClient" + BS + "GameObjectDisplayInfo.dbc")
    if not d:
        raise SystemExit("GameObjectDisplayInfo.dbc not found in the Cata client")
    rc, fc, rs, ss = struct.unpack("<4I", d[4:20])
    base, sb = 20, 20 + rc * rs
    idx = {struct.unpack_from("<I", d, base + i * rs)[0]: i for i in range(rc)}

    def s(o):
        if o == 0:
            return ""
        e = d.find(b"\0", sb + o)
        return d[sb + o:e].decode("utf-8", "replace") if e >= 0 else ""

    def row19(i):
        o = base + idx[i] * rs
        raw = [struct.unpack_from("<I", d, o + k * 4)[0] for k in range(19)]
        out = []
        for k, v in enumerate(raw):
            if k in STRINGS:
                out.append(s(v))
            elif k in FLOATS:
                out.append(struct.unpack("<f", struct.pack("<I", v))[0])
            else:
                out.append(v)
        return out
    return idx, row19, fc


def main():
    idx, row19, cata_fc = load_cata()
    absent = [x for x in MISSING if x not in idx]
    if absent:
        raise SystemExit("not in the Cata client: %s" % absent)
    rows = [row19(x) for x in MISSING]
    print("Cata GameObjectDisplayInfo fields=%d -> taking the first 19" % cata_fc)

    # ---------- 1. the overlay SQL ----------
    ids = ",".join(str(x) for x in MISSING)
    with open(OUT_SQL, "w", encoding="utf-8", newline=NL) as fh:
        w = fh.write
        w("-- 97_gameobject_displays.sql -- map 751 Lordaeron extension, DB step 36." + NL)
        w("--" + NL)
        w("-- GENERATED by Custom/Documentation/scripts/gen_map751_go_displays.py." + NL + "--" + NL)
        w("-- The 18 GameObjectDisplayInfo rows map 751's gameobjects reference and 3.3.5" + NL)
        w("-- does not have. Symptom:" + NL)
        w("--   Gameobject (GUID: ... Entry 4808816 GoType: 3) has an invalid displayId" + NL)
        w("--   (10615), not loaded." + NL)
        w("-- 146 spawns over 49 gameobject entries never load. NOTHING on any other map" + NL)
        w("-- uses these 18 displays, so this cannot disturb existing content." + NL + "--" + NL)
        w("-- LAYOUT: ours is Cata's FIRST 19 FIELDS. Cata's table is 21 fields / 84 bytes," + NL)
        w("-- ours 19 / 76; the extra two are Cata additions and are dropped. Verified over" + NL)
        w("-- 150 ids present in both clients: fields 0-11 and 18 agree 100%, and only the" + NL)
        w("-- GeoBox floats (12-17) differ, on ~10% of rows -- Blizzard recalculating bounds," + NL)
        w("-- not a misalignment. A layout error would fail ~100% on specific fields." + NL + "--" + NL)
        w("-- No model work: all 18 referenced models, including the Cata-only expansion03" + NL)
        w("-- worgen and deepholm doodads, are ALREADY in the live client from earlier" + NL)
        w("-- downport passes (every live archive probed for each path, .mdx and .m2)." + NL + "--" + NL)
        w("-- THE OVERLAY ALONE IS NOT ENOUGH. The server reads its binary" + NL)
        w("-- data/dbc/GameObjectDisplayInfo.dbc to decide whether a spawn loads -- proven" + NL)
        w("-- for CreatureDisplayInfo in 2026-08-02. The rebuilt DBC ships alongside this" + NL)
        w("-- file and must reach data/dbc; the client patches only gate RENDERING." + NL)
        w(NL)
        w("DELETE FROM %s WHERE %s IN (%s);" % (bt("gameobjectdisplayinfo_dbc"), bt("ID"), ids) + NL + NL)
        w("INSERT INTO %s" % bt("gameobjectdisplayinfo_dbc") + NL)
        w("  (%s)" % ", ".join(bt(c) for c in COLS) + NL)
        w("VALUES" + NL)
        out = []
        for r in rows:
            vals = []
            for k, v in enumerate(r):
                if k in STRINGS:
                    vals.append("'" + str(v).replace(BS, BS + BS).replace("'", "''") + "'")
                elif k in FLOATS:
                    vals.append(repr(round(float(v), 6)))
                else:
                    vals.append(str(v))
            out.append("(" + ", ".join(vals) + ")")
        w(("," + NL).join(out) + ";" + NL + NL)
        w("-- ---------------------------------------------------------------------------" + NL)
        w("-- Verification" + NL)
        w("-- ---------------------------------------------------------------------------" + NL)
        w("SELECT 'display rows added (want %d)' AS what, COUNT(*) AS n" % len(MISSING) + NL)
        w("  FROM %s WHERE %s IN (%s)" % (bt("gameobjectdisplayinfo_dbc"), bt("ID"), ids) + NL)
        w("UNION ALL SELECT 'map-751 GO spawns they unblock (want 146)', COUNT(*)" + NL)
        w("  FROM %s g JOIN %s t ON t.%s = g.%s" % (bt("gameobject"), bt("gameobject_template"),
                                                    bt("entry"), bt("id")) + NL)
        w("  WHERE g.%s = 751 AND t.%s IN (%s)" % (bt("map"), bt("displayId"), ids) + NL)
        w("UNION ALL SELECT '  ...distinct GO entries (want 49)', COUNT(DISTINCT t.%s)" % bt("entry") + NL)
        w("  FROM %s g JOIN %s t ON t.%s = g.%s" % (bt("gameobject"), bt("gameobject_template"),
                                                    bt("entry"), bt("id")) + NL)
        w("  WHERE g.%s = 751 AND t.%s IN (%s);" % (bt("map"), bt("displayId"), ids) + NL + NL)
        w("-- must be empty: a map-751 gameobject still pointing at a display that is in" + NL)
        w("-- neither the overlay nor the shipped DBC" + NL)
        w("SELECT 'PROBLEM: GO display still missing' AS problem, t.%s, t.%s, COUNT(*) AS spawns"
          % (bt("entry"), bt("displayId")) + NL)
        w("FROM %s g JOIN %s t ON t.%s = g.%s" % (bt("gameobject"), bt("gameobject_template"),
                                                  bt("entry"), bt("id")) + NL)
        w("WHERE g.%s = 751 AND t.%s > 0" % (bt("map"), bt("displayId")) + NL)
        w("  AND t.%s NOT IN (%s)" % (bt("displayId"), ids) + NL)
        w("  AND NOT EXISTS (SELECT 1 FROM %s d WHERE d.%s = t.%s)"
          % (bt("gameobjectdisplayinfo_dbc"), bt("ID"), bt("displayId")) + NL)
        w("GROUP BY t.%s, t.%s;" % (bt("entry"), bt("displayId")) + NL)
    print("wrote %s" % OUT_SQL)

    # ---------- 2. the CSV ----------
    with open(CSV_PATH, encoding="utf-8", newline="") as fh:
        r = csv.reader(fh)
        hdr = next(r)
        crows = [x for x in r if x and x[0].strip() != ""]
    assert hdr == COLS, "CSV header does not match the expected 19 columns"
    have = {x[0] for x in crows}
    added = 0
    for r_ in rows:
        if str(r_[0]) in have:
            continue
        crows.append([("%g" % v) if isinstance(v, float) else str(v) for v in r_])
        added += 1
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator=NL, quoting=csv.QUOTE_ALL)
    w.writerow(hdr)
    for x in crows:
        w.writerow(x)
    open(CSV_PATH, "w", encoding="utf-8", newline="").write(buf.getvalue())
    print("GameObjectDisplayInfo.csv: %d rows (+%d)" % (len(crows), added))

    # ---------- 3. the DBC ----------
    d = open(DBC_PATH, "rb").read()
    rc, fc, rs, ss = struct.unpack("<4I", d[4:20])
    assert (fc, rs) == (19, 76), (fc, rs)
    base, sb = 20, 20 + rc * rs
    recs = bytearray(d[base:sb])
    strb = bytearray(d[sb:sb + ss])
    present = {struct.unpack_from("<I", d, base + i * rs)[0] for i in range(rc)}
    seen, off = {}, 0
    while off < len(strb):
        e = strb.find(b"\0", off)
        if e < 0:
            break
        seen.setdefault(strb[off:e].decode("utf-8", "replace"), off)
        off = e + 1
    seen[""] = 0

    def addstr(t):
        if t in seen:
            return seen[t]
        o = len(strb)
        strb.extend(t.encode("utf-8") + b"\0")
        seen[t] = o
        return o

    n = 0
    for r_ in rows:
        if r_[0] in present:
            continue
        rec = bytearray()
        for k, v in enumerate(r_):
            if k in STRINGS:
                rec += struct.pack("<I", addstr(v))
            elif k in FLOATS:
                rec += struct.pack("<f", float(v))
            else:
                rec += struct.pack("<I", int(v) & 0xFFFFFFFF)
        assert len(rec) == rs
        recs += rec
        n += 1
    out = b"WDBC" + struct.pack("<4I", rc + n, fc, rs, len(strb)) + bytes(recs) + bytes(strb)
    open(DBC_PATH, "wb").write(out)
    print("GameObjectDisplayInfo.dbc: %d -> %d records, string block %d -> %d"
          % (rc, rc + n, ss, len(strb)))


if __name__ == "__main__":
    main()
