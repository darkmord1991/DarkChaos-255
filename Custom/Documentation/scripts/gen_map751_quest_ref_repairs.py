#!/usr/bin/env python3
"""Emit Plaguelands/96_quest_reference_repairs.sql -- the fourth class of post-import
quest-validation errors: quest fields pointing at things this server does not have.

Four groups, each traced to its source before being "fixed". Three of the four are
repaired by making the DATA HONEST rather than by inventing content, and the reasoning
is written into the emitted SQL so the choice is reviewable.
"""
import re

ROOT = "K:/Dark-Chaos/DarkChaos-255-Master/Custom/"
OUT = ROOT + "Custom feature SQLs/worlddb/Plaguelands/96_quest_reference_repairs.sql"
NL = chr(10)
BT = chr(96)

# our 138 item_template columns, taken from the file 94_ already emits
sql94 = open(ROOT + "Custom feature SQLs/worlddb/Plaguelands/94_item_template.sql", encoding="utf-8").read()
m = re.search(r"INSERT INTO .item_template. \((.*?)\) VALUES", sql94, re.S)
COLS = [c.strip().strip(BT) for c in m.group(1).split(",")]
assert len(COLS) == 138, len(COLS)

# the 28 columns nelt_world.item_template does not have (verified against
# INFORMATION_SCHEMA); all zero-defaulted and meaningless for a quest item
OURS_ONLY = {
    "ammo_type", "arcane_res", "armor", "block", "DisenchantID", "dmg_max1", "dmg_max2",
    "dmg_min1", "dmg_min2", "dmg_type1", "dmg_type2", "fire_res", "FoodType", "frost_res",
    "holy_res", "maxMoneyLoot", "minMoneyLoot", "nature_res", "RequiredDisenchantSkill",
    "ScalingStatValue", "ScriptName", "shadow_res", "spellppmRate_1", "spellppmRate_2",
    "spellppmRate_3", "spellppmRate_4", "spellppmRate_5", "VerifiedBuild",
}
SHARED = [c for c in COLS if c not in OURS_ONLY]
assert len(SHARED) == 110, len(SHARED)

ZONE_4706 = [27290, 27322, 27333, 27342, 27349, 27350, 27364, 27401, 27405, 27406, 27423]
ZONE_5287 = [28704]

DEAD_SPELLS = {89550: [28219, 28220], 89781: [28221, 28222], 89669: [28228],
               94710: [13980], 95818: [14435]}
LIVE_SPELLS = [83716, 83865, 83935, 88763, 88794, 89457, 90414, 91768, 92229, 99387]

CHAINS = {
    26867: 26858, 26943: 26939, 27045: 27056, 27181: 27193, 27277: 27400, 27278: 27395,
    27279: 27396, 27281: 27365, 27282: 27402, 27283: 27404, 27298: 27434, 27304: 27403,
    27331: 27435, 27332: 27436, 27334: 27437, 27335: 27439, 27350: 27360, 27513: 27518,
    27718: 25924, 28164: 27441, 28290: 28457, 28297: 28461, 28298: 28463, 28299: 28459,
    28300: 28458, 28302: 28466, 28303: 28473, 28304: 28474, 28307: 28475, 28309: 28477,
    28323: 28478, 28344: 28345, 28557: 27003, 28581: 27963, 28667: 28418, 28671: 25674,
    28677: 27587, 29157: 29219,
}

HEADER = """-- 96_quest_reference_repairs.sql -- map 751 Lordaeron extension, DB step 35.
--
-- GENERATED by Custom/Documentation/scripts/gen_map751_quest_ref_repairs.py.
--
-- The fourth class of post-import quest-validation errors: quest fields pointing at
-- things this server does not have. 68 log lines over four groups.
--
-- THREE OF THE FOUR ARE FIXED BY MAKING THE DATA HONEST, NOT BY INVENTING CONTENT.
-- Each group was traced to its source before deciding, and the reasoning is here so
-- the choice is reviewable rather than implied.
--
-- ============================================================================
-- 1. Item 68647 -- REAL FIX. The one item 94_ could not build ("absent from
--    Item-sparse"), and it blocks quest 29377 "A Time to Break Down" twice
--    (StartItem and ItemDrop2). It is not in the Cata client, but it IS in
--    nelt_world.item_template -- a full 3.3.5-format row, "Dousing Agent",
--    class 12 (Quest), displayid 55112, which our ItemDisplayInfo already has.
--    So it needs no client-side work at all.
--
--    SCHEMA TRAP: both tables have 138 columns but only 110 share a name, so a
--    SELECT * would silently misalign. The 110 are named explicitly below. The 28
--    we have and nelt does not are armor/damage/resistance/ppm fields that default
--    to 0 and mean nothing for a quest item.
--
-- 2. ZoneOrSort -- REAL FIX, by remapping to the parent zone that exists.
--      4706 = Jintha'Alor      (11 quests) -> 47, The Hinterlands
--      5287 = Darkspear Strand  (1 quest)  -> 14, Durotar
--    Both are genuine Cata AreaTable rows (confirmed in the 4.3.4 client) that
--    3.3.5 does not have. Rather than add AreaTable rows -- a DBC rebuild plus an
--    AreaBit, and they would be the only subzone sorts in the band -- they take
--    their PARENT zone. That matches the convention the rest of the import already
--    uses: every other map-751 quest sorts under a plain stock zone id
--    (47 x67, 267 x50, 45 x38, 85 x36, 130 x19 ...). 4706 was the only invalid
--    one, and 47 is where its 67 siblings already sort.
--
--    Note 28704 "Warchief's Command: The Cape of Stranglethorn!" is Durotar
--    bulletin-board content that leaked into the import and has no questgiver at
--    all. Fixing its sort clears the log line; it stays unreachable either way.
--
-- 3. RewardSpell -- SPLIT. Of the 15 missing spells, 10 exist in the Cata 4.3.4
--    client and are added to the spell downport in 88_ (now 237 spells -- RE-APPLY
--    IT). The other 5 do not exist in the 4.3.4 client AT ALL:
--        89550, 89669, 89781, 94710, 95818
--    They were removed from the game before 4.3.4, so the cata_world snapshot
--    predates its own client. There is nothing to downport. The 7 affected quests
--    get RewardSpell = 0, which is what the core already does with an invalid id --
--    this only stops it complaining. They are cosmetic / despawn-helper spells,
--    not player abilities, so nothing is lost.
--
-- 4. RewardNextQuest -- HONEST FIX, 38 chains zeroed. Every one of the 38 targets
--    exists in cata_world and has a questgiver there, so importing them was
--    considered and rejected: NOT ONE of those questgivers has a spawn on map 751,
--    and 30 of the 38 do not exist in our creature_template at all. They live in
--    Orgrimmar (Grezz Ragefist, Ormak Grimshot, Zevrost, Master Pyreanor, Sunwalker
--    Atohmo, Shadow-Walker Zuru ...), Moonglade (Loganaar), Ragefire Chasm and
--    Stranglethorn. These are Cata "now report to your class trainer" follow-ups --
--    capital-city content, not Lordaeron content.
--
--    Importing them would have produced 38 quests nobody can pick up, and grafting
--    Cata quests onto stock Orgrimmar NPCs is exactly what this project does not do
--    (the same reason 92_ leaves 337 shared quests alone). Zeroing is behaviourally
--    identical to today -- the core already ignores an invalid RewardNextQuest --
--    and makes the data say what is actually true.
-- ============================================================================

"""


def idl(xs):
    return ",".join(str(x) for x in sorted(xs))


def bt(name):
    return BT + name + BT


with open(OUT, "w", encoding="utf-8", newline=NL) as fh:
    w = fh.write
    w(HEADER)

    w("-- ---------------------------------------------------------------------------\n")
    w("-- 1. Item 68647 'Dousing Agent' -- from nelt_world, 110 explicitly named columns\n")
    w("-- ---------------------------------------------------------------------------\n")
    w("DELETE FROM %s WHERE %s = 68647;\n" % (bt("item_template"), bt("entry")))
    cols = ", ".join(bt(c) for c in SHARED)
    w("INSERT INTO %s\n  (%s)\nSELECT %s\nFROM %s.%s WHERE %s = 68647;\n\n"
      % (bt("item_template"), cols, cols, bt("nelt_world"), bt("item_template"), bt("entry")))

    w("-- the Item.dbc half, the same overlay 95_ uses\n")
    w("DELETE FROM %s WHERE %s = 68647;\n" % (bt("item_dbc"), bt("ID")))
    w("INSERT INTO %s (%s, %s, %s, %s,\n" % (bt("item_dbc"), bt("ID"), bt("ClassID"),
                                             bt("SubclassID"), bt("Sound_Override_Subclassid")))
    w("                        %s, %s, %s, %s)\n" % (bt("Material"), bt("DisplayInfoID"),
                                                     bt("InventoryType"), bt("SheatheType")))
    w("SELECT %s, %s, %s, %s, %s,\n" % (bt("entry"), bt("class"), bt("subclass"),
                                        bt("SoundOverrideSubclass"), bt("Material")))
    w("       %s, %s, %s\n" % (bt("displayid"), bt("InventoryType"), bt("sheath")))
    w("FROM %s.%s WHERE %s = 68647;\n\n" % (bt("nelt_world"), bt("item_template"), bt("entry")))

    w("-- ---------------------------------------------------------------------------\n")
    w("-- 2. ZoneOrSort -> the parent zone that exists in 3.3.5\n")
    w("-- ---------------------------------------------------------------------------\n")
    w("UPDATE %s SET %s = 47   -- Jintha'Alor -> The Hinterlands\n" % (bt("quest_template"), bt("QuestSortID")))
    w("WHERE %s IN (%s) AND %s = 4706;\n\n" % (bt("ID"), idl(ZONE_4706), bt("QuestSortID")))
    w("UPDATE %s SET %s = 14   -- Darkspear Strand -> Durotar\n" % (bt("quest_template"), bt("QuestSortID")))
    w("WHERE %s IN (%s) AND %s = 5287;\n\n" % (bt("ID"), idl(ZONE_5287), bt("QuestSortID")))

    w("-- ---------------------------------------------------------------------------\n")
    w("-- 3. RewardSpell = 0 for the 5 spells no 4.3.4 client has\n")
    w("--    (the other 10 are downported by 88_ -- re-apply it, it is now 237 spells)\n")
    w("-- ---------------------------------------------------------------------------\n")
    for sp in sorted(DEAD_SPELLS):
        w("UPDATE %s SET %s = 0 WHERE %s IN (%s) AND %s = %d;\n"
          % (bt("quest_template"), bt("RewardSpell"), bt("ID"), idl(DEAD_SPELLS[sp]),
             bt("RewardSpell"), sp))
    w("\n")

    w("-- ---------------------------------------------------------------------------\n")
    w("-- 4. RewardNextQuest = 0 -- the 38 follow-ups live outside Lordaeron\n")
    w("-- ---------------------------------------------------------------------------\n")
    for q in sorted(CHAINS):
        w("UPDATE %s SET %s = 0 WHERE %s = %d AND %s = %d;\n"
          % (bt("quest_template"), bt("RewardNextQuest"), bt("ID"), q,
             bt("RewardNextQuest"), CHAINS[q]))
    w("\n")

    w("-- ---------------------------------------------------------------------------\n")
    w("-- Verification\n")
    w("-- ---------------------------------------------------------------------------\n")
    w("SELECT 'item 68647 built (want 1)' AS what, COUNT(*) AS n FROM %s WHERE %s = 68647\n"
      % (bt("item_template"), bt("entry")))
    w("UNION ALL SELECT '  ...and its item_dbc row (want 1)', COUNT(*) FROM %s WHERE %s = 68647\n"
      % (bt("item_dbc"), bt("ID")))
    w("UNION ALL SELECT 'quests still sorted to a dead zone (want 0)', COUNT(*)\n")
    w("  FROM %s WHERE %s IN (4706, 5287)\n" % (bt("quest_template"), bt("QuestSortID")))
    w("UNION ALL SELECT '  ...moved to The Hinterlands (want %d)', COUNT(*)\n" % len(ZONE_4706))
    w("  FROM %s WHERE %s IN (%s) AND %s = 47\n"
      % (bt("quest_template"), bt("ID"), idl(ZONE_4706), bt("QuestSortID")))
    w("UNION ALL SELECT '  ...moved to Durotar (want %d)', COUNT(*)\n" % len(ZONE_5287))
    w("  FROM %s WHERE %s IN (%s) AND %s = 14\n"
      % (bt("quest_template"), bt("ID"), idl(ZONE_5287), bt("QuestSortID")))
    w("UNION ALL SELECT 'quests still rewarding a dead spell (want 0)', COUNT(*)\n")
    w("  FROM %s WHERE %s IN (%s)\n" % (bt("quest_template"), bt("RewardSpell"), idl(DEAD_SPELLS)))
    w("UNION ALL SELECT 'chains still pointing at a missing quest (want 0)', COUNT(*)\n")
    w("  FROM %s q WHERE q.%s > 0\n" % (bt("quest_template"), bt("RewardNextQuest")))
    w("    AND NOT EXISTS (SELECT 1 FROM %s n WHERE n.%s = q.%s);\n\n"
      % (bt("quest_template"), bt("ID"), bt("RewardNextQuest")))

    w("-- must be empty: a quest reward spell we kept that is in neither spell_dbc nor\n")
    w("-- the 10 that 88_ adds\n")
    w("SELECT 'PROBLEM: reward spell still missing' AS problem, %s, %s\n" % (bt("ID"), bt("RewardSpell")))
    w("FROM %s WHERE %s >= 70000\n" % (bt("quest_template"), bt("RewardSpell")))
    w("  AND NOT EXISTS (SELECT 1 FROM %s d WHERE d.%s = %s)\n"
      % (bt("spell_dbc"), bt("ID"), bt("RewardSpell")))
    w("  AND %s NOT IN (%s);\n\n" % (bt("RewardSpell"), idl(LIVE_SPELLS)))

    w("-- must be empty: item 68647 landed but with a display the client cannot draw\n")
    w("SELECT 'PROBLEM: 68647 display missing' AS problem, i.%s, i.%s\n" % (bt("entry"), bt("displayid")))
    w("FROM %s i WHERE i.%s = 68647\n" % (bt("item_template"), bt("entry")))
    w("  AND NOT EXISTS (SELECT 1 FROM %s d WHERE d.%s = i.%s);\n"
      % (bt("itemdisplayinfo_dbc"), bt("ID"), bt("displayid")))

print("wrote %s" % OUT)
print("  shared item_template columns : %d of 138" % len(SHARED))
print("  ZoneOrSort remaps            : %d -> 47, %d -> 14" % (len(ZONE_4706), len(ZONE_5287)))
print("  RewardSpell zeroed           : %d quests over %d dead spells"
      % (sum(len(v) for v in DEAD_SPELLS.values()), len(DEAD_SPELLS)))
print("  RewardNextQuest zeroed       : %d chains" % len(CHAINS))
print("  spells handed to 88_         : %d" % len(LIVE_SPELLS))
