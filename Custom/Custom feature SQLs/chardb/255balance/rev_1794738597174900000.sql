-- DarkChaos: remove trained talent-spell ranks from characters that do not have the talent
--
-- Until 2026-11-15 the DCFirstStart auto-learn taught every trainer spell of a character's level, ignoring
-- the trainer's rule that a talent spell's higher ranks need the talent. So characters were given, for
-- example, Arcane Barrage, Living Bomb, Ice Barrier, Mortal Strike or Mangle ranks without the talent. The
-- fixed auto-learn no longer does that; this file removes what it handed out before.
--
-- Covered: the 43 talent spells with trained higher ranks (230 rank spells), listed below. A rank is
-- removed only when the character has the talent in neither spec (character_talent) and does not know
-- the first rank either. Measured 2026-11-15: 19,288 rows on 3,061 characters, 14 of them not bots
-- (226 rows).
--
-- Every removed row is kept in dc_talent_rank_cleanup_backup; copy it back into character_spell to revert.
-- Re-running removes only rows that qualify at that moment. Apply to acore_chars with the worldserver
-- STOPPED: an online character keeps the spells in memory until it logs out.

