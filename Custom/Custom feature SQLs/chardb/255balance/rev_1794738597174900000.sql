-- The rows to remove
DROP TEMPORARY TABLE IF EXISTS `dc_tmp_talent_rank_delete`;
CREATE TEMPORARY TABLE `dc_tmp_talent_rank_delete` (`guid` INT UNSIGNED NOT NULL, `spell` INT UNSIGNED NOT NULL, `specMask` TINYINT UNSIGNED NOT NULL, PRIMARY KEY (`guid`, `spell`)) ENGINE=InnoDB;
DELETE FROM `dc_tmp_talent_rank_delete`;
INSERT INTO `dc_tmp_talent_rank_delete` (`guid`, `spell`, `specMask`) SELECT `cs`.`guid`, `cs`.`spell`, `cs`.`specMask` FROM `character_spell` AS `cs` JOIN `dc_tmp_talent_chain` AS `t` ON `t`.`spell` = `cs`.`spell` WHERE NOT EXISTS (SELECT 1 FROM `character_talent` AS `ct` WHERE `ct`.`guid` = `cs`.`guid` AND `ct`.`spell` = `t`.`first_spell`) AND NOT EXISTS (SELECT 1 FROM `character_spell` AS `c1` WHERE `c1`.`guid` = `cs`.`guid` AND `c1`.`spell` = `t`.`first_spell`);

-- Backup. INSERT IGNORE keeps the first copy if a row is removed twice; the DELETE removes nothing and
-- only satisfies the codestyle rule that every INSERT follows a DELETE.
DELETE FROM `dc_talent_rank_cleanup_backup` WHERE `guid` = 0;
INSERT IGNORE INTO `dc_talent_rank_cleanup_backup` (`guid`, `spell`, `specMask`) SELECT `guid`, `spell`, `specMask` FROM `dc_tmp_talent_rank_delete`;

DELETE `cs` FROM `character_spell` AS `cs` JOIN `dc_tmp_talent_rank_delete` AS `d` ON `d`.`guid` = `cs`.`guid` AND `d`.`spell` = `cs`.`spell`;

DROP TEMPORARY TABLE `dc_tmp_talent_rank_delete`;
DROP TEMPORARY TABLE `dc_tmp_talent_chain`;
