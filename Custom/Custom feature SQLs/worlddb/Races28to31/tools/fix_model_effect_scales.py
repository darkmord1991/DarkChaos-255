#!/usr/bin/env python3
r"""
fix_model_effect_scales.py - repair zero effect scales in CreatureModelData.

No stock row has AttachedEffectScale 0, but 93 custom rows did. The client multiplies every effect attached
to a model by that value, so spell effects on those models drew at size zero: on a Zandalari Troll the
level-up column was gone, leaving only a small flame at the feet. WorldEffectScale does the same for world
effects. Run this after any import that adds models, it changes nothing when the table is clean.

Vulpera and Zandalari are worse. Ascension's rows for them are shifted by a column (width holds the height,
height holds 1, the 1 for AttachedEffectScale sits in MissileCollisionRadius), so both also moved with a 1
yard collision radius instead of 0.3, and the server took their line of sight from 1 yard up. Those rows get
proven values: Goblin's for Vulpera, Pandaren's for Zandalari. Mounts and pets with the same shifted collision
get the default box that the rest of the table uses.

    python fix_model_effect_scales.py

Only these four rows are in the server's creaturemodeldata_dbc overlay, so ../21_model_data_fix.sql is short.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_races28to31 as races  # noqa: E402

SQL_OUT = os.path.join(HERE, "..", "21_model_data_fix.sql")
OVERLAY = os.path.join(HERE, "..", "..", "AlliedRaces", "11_dbc_overlay.sql")
PLAYER_COLLISION = {"503902": ("0.5556", "1.389"), "503903": ("0.5556", "1.389"),
                    "503904": ("0.611112", "2.03128"), "503905": ("0.611112", "2.03128")}
# Mounts and pets from the same donor rows: the width slot holds the default height.
SHIFTED_HEIGHT = "2.03128"
DEFAULT_COLLISION = ("0.6111", "2.03128")


def repair(table):
    ix = table.index
    changed = 0
    for row in table.rows:
        before = list(row)
        if float(row[ix["AttachedEffectScale"]]) == 0:
            # The shifted rows carry the 1 they lost one column along.
            if float(row[ix["MissileCollisionRadius"]]) == 1:
                row[ix["MissileCollisionRadius"]] = "0"
            row[ix["AttachedEffectScale"]] = "1"
        if float(row[ix["WorldEffectScale"]]) == 0:
            row[ix["WorldEffectScale"]] = "1"
        if row[ix["CollisionWidth"]] == SHIFTED_HEIGHT and float(row[ix["CollisionHeight"]]) <= 1:
            row[ix["CollisionWidth"]], row[ix["CollisionHeight"]] = DEFAULT_COLLISION
        if row[0] in PLAYER_COLLISION:
            row[ix["CollisionWidth"]], row[ix["CollisionHeight"]] = PLAYER_COLLISION[row[0]]
        changed += row != before
    return changed


def write_sql(table):
    lines = ["-- Vulpera and Zandalari: repaired CreatureModelData rows, for the server's overlay.",
             "-- GENERATED by tools/fix_model_effect_scales.py. Safe to run again."]
    ix = table.index
    for row in table.rows:
        if row[0] in PLAYER_COLLISION:
            lines.append("UPDATE `creaturemodeldata_dbc` SET `CollisionWidth` = %s, `CollisionHeight` = %s, "
                         "`WorldEffectScale` = %s, `AttachedEffectScale` = %s, `MissileCollisionRadius` = %s "
                         "WHERE `ID` = %s;" % (row[ix["CollisionWidth"]], row[ix["CollisionHeight"]],
                                               row[ix["WorldEffectScale"]], row[ix["AttachedEffectScale"]],
                                               row[ix["MissileCollisionRadius"]], row[0]))
    with open(SQL_OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def update_overlay(table):
    """The old overlay deletes and reinserts these rows, so running it again must not bring the defect back."""
    with open(OVERLAY, encoding="utf-8", newline="") as f:
        lines = f.read().split("\n")
    wanted = {row[0]: row for row in table.rows if row[0] in PLAYER_COLLISION}
    for i, line in enumerate(lines):
        for key, row in wanted.items():
            if line.startswith("(" + key + ", 2052,"):
                lines[i] = races.sql_values(row) + line[line.rindex(")") + 1:]
    with open(OVERLAY, "w", encoding="utf-8", newline="") as f:
        f.write("\n".join(lines))


def main():
    before = races.semantic("CreatureModelData")
    table = races.CsvTable("CreatureModelData")
    changed = repair(table)
    table.save()
    subprocess.check_call([sys.executable, races.CSV2WDBC, "--csv", table.path, "--out",
                           os.path.join(races.DBC_DIR, "CreatureModelData.dbc"), "--table", "CreatureModelData"],
                          stdout=subprocess.DEVNULL)
    after = races.semantic("CreatureModelData")
    lost = [key for key in before if key not in after]
    moved = [key for key, cells in before.items() if key in after and after[key] != cells]
    print("rows repaired %d, compiled rows %d -> %d, lost %d, changed %d" % (changed, len(before), len(after), len(lost), len(moved)))
    if lost or len(moved) != changed:
        raise SystemExit("unexpected change in the compiled table")
    write_sql(table)
    update_overlay(table)
    return 0


if __name__ == "__main__":
    sys.exit(main())
