-- DarkChaos: maps 750 / 751 - private copies of the shared grey quests, and the old-world questlines unlinked
--
-- 1. OLD-WORLD QUESTLINES. 102 quests handed out by map 750/751 NPCs send the player back to the old
--    world: the turn-in, an objective, the prerequisite or the follow-up only exists on a stock map, or it
--    is a Warchief's Command / Hero's Call board quest. Their 750/751 givers are unlinked (kind RC/RG).
--    The quests themselves stay: the ids are shared, the old world keeps offering them unchanged.
--
-- 2. CLONES. 175 stock quests are handed out by our clone NPCs on 750/751 AND by the stock NPCs in the old
--    world, so their level could not be raised without touching maps 0/1. Each gets a private copy at
--    raw id + 200000 (the 200000-299999 window was empty), scaled like the rest of the continent
--    (QuestLevel -1, MinLevel = band floor - 2), and only the DC NPCs are switched over to it:
--      * givers that spawn only in the DC world: raw link removed, clone link added (kind CS/GS);
--      * turn-ins that spawn only in the DC world, or never spawn (summoned): clone link added, raw link
--        kept so a player still holding the raw quest can finish it (kind CE/GE);
--      * a link is never added to or removed from an NPC or object that also spawns in the old world -
--        the guards below re-check that at apply time.
--    Copied with the quest: quest_template_addon (chain fields remapped only inside the clone set, sign of
--    PrevQuestID/ExclusiveGroup kept, reward mail cleared as in HyjalCata/167_), quest_details,
--    quest_offer_reward, quest_request_items, their locales, and quest_poi moved from map 0/1 onto 750/751
--    with the WorldMapArea of the zone the points lie in (POIs that point off the continent are dropped).
--    SmartAI rows and gameobject data of DC-owned entries are remapped in place. Conditions are extended,
--    never edited: a positive quest reference gets an OR copy with the clone id, a negative one an extra
--    AND row; for a player who never holds a clone (everyone in the old world) nothing changes. Added rows
--    carry the comment prefix 'DC quest clone'.
--
-- Chains are moved as a whole: a questline is cloned only if every shared member of it can be. 14 quests
-- in 8 chains stay raw because a member is a battleground/PvP or seasonal quest.
--
-- Helper tables dc_quest_clone (source -> clone) and dc_quest_link (every link this file moved, added or
-- removed) stay in the DB as the record for a revert. Idempotent. Apply against acore_world.
-- Not handled: quest REWARDS are the stock items (level 50-60). A reward rescale like HyjalCata/309_ is a
-- separate step; dc_quest_clone is its input.

