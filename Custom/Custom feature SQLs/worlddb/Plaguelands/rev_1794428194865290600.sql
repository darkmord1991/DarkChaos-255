-- DarkChaos: map 751 quest-reward gear onto the continued item curve (130 -> 430, 160 -> 520)
--
-- The 751 rewards were rescaled on 11-10 to almost flat item levels (130: 392 ... 152: 423), so from level
-- 115 to ~137 the best wearable green/blue sat flat at 396 and plate/mail stopped rising at 145. Approved
-- 11-11: keep map 750 (80-113) as is and continue its slope - green item level T(L) = 388 + 2.5*(L-113) up to
-- level 130 (430), then 430 + 3*(L-130) up to 160 (520); blue +8, epic +16.
--
-- 350 items: every gear reward of the map-751 quests (RequiredLevel 130-159). RequiredLevel is unchanged;
-- ItemLevel goes to T(RequiredLevel) + quality offset. The stats were built on 11-10 from the stat budget
-- 0.00207 * ilvl^2.13 * slot weight * quality, so each stat is scaled by (new ilvl / old ilvl)^2.13 - the
-- stat mix and the 40% single-stat cap carry over. Armor and weapon damage come from the Cata curve DBCs at the
-- new item level (weapon speed unchanged); sell/buy price scale with the stats. An item is never lowered.
--
-- Originals go to dc_item_curve_backup on the FIRST run only (restore statement at the end). Re-running
-- writes the same absolute values. Clients see the new stats once their item cache refreshes.

