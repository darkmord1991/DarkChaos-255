-- Path of Chaos: the book of tasks and milestones, read at startup and by `.path reload`.
--
-- A task id is permanent: progress in acore_chars.dc_path_progress is keyed by it, so renumbering
-- a row hands every account the progress of a different task. Disable a row instead of reusing it.
--
-- objective_type holds a DarkChaos::Path::ObjectiveType (DCPath.h), which also says what the
-- filter means. reward_points are Shop Points. A row may also pay one item stack and one
-- collectible (reward_collection_type is a DCCollection::CollectionType).

CREATE TABLE IF NOT EXISTS `dc_path_categories` (
  `id` TINYINT UNSIGNED NOT NULL,
  `sort_order` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `name` VARCHAR(64) NOT NULL,
  `description` VARCHAR(255) NOT NULL DEFAULT '',
  `icon` VARCHAR(64) NOT NULL DEFAULT '' COMMENT 'File name under Interface\\Icons',
  `enabled` TINYINT(1) NOT NULL DEFAULT 1,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Path of Chaos categories';

CREATE TABLE IF NOT EXISTS `dc_path_tasks` (
  `id` SMALLINT UNSIGNED NOT NULL,
  `category_id` TINYINT UNSIGNED NOT NULL,
  `sort_order` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `name` VARCHAR(80) NOT NULL,
  `description` VARCHAR(255) NOT NULL DEFAULT '',
  `icon` VARCHAR(64) NOT NULL DEFAULT '' COMMENT 'File name under Interface\\Icons',
  `objective_type` TINYINT UNSIGNED NOT NULL,
  `objective_filter` INT UNSIGNED NOT NULL DEFAULT 0,
  `objective_target` INT UNSIGNED NOT NULL DEFAULT 1,
  `prev_task_id` SMALLINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Must be complete before this reward can be claimed',
  `reward_points` INT UNSIGNED NOT NULL DEFAULT 0,
  `reward_item_id` INT UNSIGNED NOT NULL DEFAULT 0,
  `reward_item_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `reward_collection_type` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `reward_collection_entry` INT UNSIGNED NOT NULL DEFAULT 0,
  `enabled` TINYINT(1) NOT NULL DEFAULT 1,
  PRIMARY KEY (`id`),
  KEY `idx_category` (`category_id`, `sort_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Path of Chaos tasks';

