-- Cata stores neither `armor` nor weapon `dmg_min/dmg_max` in the item data --
-- both are DERIVED at runtime from ItemLevel + Quality + slot via DBC curves.
-- `99_zone_gear_statfill.sql` (Phase 1) filled the primary stats from the Cata
-- ItemSparse, but deliberately left these two, so every one of the zone's own
-- drops had **0 armor and 0 weapon damage**: 459 armor pieces and 168 weapons
-- across maps 750 + 861.
--
-- Generated by `Custom/Documentation/scripts/gen_zone_gear_armor_dmg.py` from
-- the real Cata 4.3.4 curves (ItemDamage{OneHand,TwoHand,+Caster variants,
-- Ranged,Wand}, ItemArmor{Total,Quality,Shield}, ArmorLocation), extracted from
-- K:\UntouchedClients\Cata\Data\enUS\{expansion3-,}locale-enUS.MPQ.
--
--   weapon dps = ItemDamage<Type>[ItemLevel][Quality]
--                avg = dps * delay / 1000
--                dmg_min = round(avg * 0.85), dmg_max = round(avg * 1.15)
--   armor      = round( ItemArmorTotal[ilvl][armorType]
--                       * ItemArmorQuality[ilvl][Quality]
--                       * ArmorLocation[InventoryType][armorType] )
--   shield     = round( ItemArmorShield[ilvl][Quality] )
--
-- Covered: 167 weapons + 406 armor pieces = 573 items.
-- Skipped (54, all correct): 51 rows at class 4 / subclass 0 -- neck, ring,
-- trinket, relic and held-in-off-hand, which carry no armor by design; 1 thrown
-- weapon (Cata ships no ItemDamage curve for subclass 16); 2 deprecated
-- "buckler" rows (subclass 5) on head-slot items.
--
-- 🔴 Generator fix made while producing this: `ArmorLocation.dbc` defines only
-- the canonical slots, and has an ALL-ZERO row for InventoryType 20 (Robe).
-- Robes are a chest variant and must be looked up as InventoryType 5, or the
-- 10 robes in this set come out at armor = 0 -- re-creating the exact bug this
-- file exists to fix. The generator now maps 20 -> 5 and refuses to emit any
-- `armor = 0`.
--
-- Idempotent: plain UPDATEs keyed on entry. Run AFTER 99_.
-- ---------------------------------------------------------------------------

