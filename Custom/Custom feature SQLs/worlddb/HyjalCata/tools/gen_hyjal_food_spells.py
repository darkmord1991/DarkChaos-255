#!/usr/bin/env python3
"""
Hyjal Frontier 80-130 consumables -- mirror the 28 client spells onto the server.

The zone's food/water set (items 400800-400823 -- 24 items, live and already stocked
on 162 npc_vendor rows) casts spells 300550-300569 and 300580-300587. Those 28 spells
ARE present in the client's Spell.dbc (they ship in Custom/CSV DBC/Spell.csv) but were
absent from acore_world.spell_dbc, so the server could not cast a single one of them:
the whole consumable set was purchasable and inert.

IMPORTANT -- what this generator does NOT do: it does not author or clone anything.
An earlier draft cloned stock donors (45548 Food / 43183 Drink / 43185 Healing Potion /
43186 Restore Mana / 33256 Well Fed) and invented per-tier amounts, which was wrong on
two counts: it would have appended 28 DUPLICATE ids to Spell.csv, and it would have
given the server different numbers from the ones the client already renders in the
tooltip. The client rows are authoritative; this reads them back and mirrors them.

So: read the 28 existing rows out of Custom/CSV DBC/Spell.csv and emit them as
acore_world.spell_dbc rows, converting the 232-column client layout to the 234-column
server layout with the same two padding inserts gen_hyjal_spell_downport_r19.py uses
(r[0:13] + pad + r[13] + pad + r[14:]  ->  ShapeshiftMask/unk_320_2/ShapeshiftExclude/
unk_320_3). Nothing else changes, so client tooltip and server behaviour cannot drift.

Emits: <out>/146_food_spells_dbc.sql   (server rows only -- the client already has them)

Usage: python gen_hyjal_food_spells.py [outdir]
"""
import csv, os, sys

REPO = "K:/Dark-Chaos/DarkChaos-255-Master/"
SPELL_CSV = REPO + "Custom/CSV DBC/Spell.csv"
OUT = sys.argv[1] if len(sys.argv) > 1 else "k:/tmp/hyjal_food/"

WANT = set(range(300550, 300570)) | set(range(300580, 300588))   # 20 + 8 = 28

csv.field_size_limit(10 * 1024 * 1024)

rows, header = {}, None
with open(SPELL_CSV, newline="", encoding="utf-8-sig") as f:
    rd = csv.reader(f)
    header = next(rd)
    for row in rd:
        if not row:
            continue
        try:
            i = int(row[0])
        except ValueError:
            continue
        if i in WANT:
            rows[i] = list(row)

missing = sorted(WANT - set(rows))
if missing:
    raise SystemExit(f"these ids are not in the client Spell.csv either: {missing}")

IDX = {n: i for i, n in enumerate(header)}
NAME = IDX.get("Name_Lang_enUS")
EFF1, EFF2 = IDX.get("Effect_1"), IDX.get("Effect_2")
BP1, DS1 = IDX.get("EffectBasePoints_1"), IDX.get("EffectDieSides_1")
AURA1 = IDX.get("EffectAura_1")

sql_rows, report = [], []
for i in sorted(rows):
    r = rows[i]
    v = r[0:13] + ["0"] + [r[13]] + ["0"] + r[14:]
    assert len(v) == 234, f"{i}: got {len(v)} columns"
    esc = lambda x: str(x).replace("\\", "\\\\").replace("'", "\\'")
    sql_rows.append("(" + ",".join("'" + esc(x) + "'" for x in v) + ")")
    report.append(f"  [{i}] {r[NAME]!r:34} eff {r[EFF1]}/{r[EFF2] or '-'} aura {r[AURA1]} "
                  f"base {r[BP1]} die {r[DS1]}")

os.makedirs(OUT, exist_ok=True)
sql_path = os.path.join(OUT, "146_food_spells_dbc.sql")
ids = ",".join(str(i) for i in sorted(rows))
with open(sql_path, "w", encoding="utf-8", newline="\n") as f:
    f.write(f"""-- ---------------------------------------------------------------------------
-- 146  Hyjal Frontier -- server-side spell_dbc for the 28 consumable spells
-- ---------------------------------------------------------------------------
-- Items 400800-400823 (24 food / water / potion items) are live and already
-- stocked on 162 npc_vendor rows, and their 28 spells (300550-300569 +
-- 300580-300587) already ship in the CLIENT's Spell.dbc. They were missing only
-- from acore_world.spell_dbc, so the server could not cast any of them: the whole
-- set was purchasable and completely inert.
--
-- These rows are a MIRROR of the client definitions, not new authoring. They are
-- read straight back out of Custom/CSV DBC/Spell.csv and converted from the
-- 232-column client layout to the 234-column server layout using the same two
-- padding inserts gen_hyjal_spell_downport_r19.py uses (ShapeshiftMask /
-- unk_320_2 / ShapeshiftExclude / unk_320_3). Because nothing is recomputed, the
-- tooltip the client already renders and the effect the server applies cannot
-- disagree -- which is exactly what would have happened had these been authored
-- from scratch with invented per-tier numbers.
--
-- NO client-side work is needed for this file: Spell.csv already has all 28
-- (verified -- appending them would have created duplicate DBC ids).
--
-- Generated by HyjalCata/tools/gen_hyjal_food_spells.py. Idempotent; needs a
-- worldserver restart.
-- ---------------------------------------------------------------------------

DELETE FROM `spell_dbc` WHERE `ID` IN ({ids});

INSERT INTO `spell_dbc` VALUES
""")
    f.write(",\n".join(sql_rows) + ";\n")

print(f"mirrored {len(sql_rows)} client spells -> {sql_path}\n")
print("\n".join(report))
