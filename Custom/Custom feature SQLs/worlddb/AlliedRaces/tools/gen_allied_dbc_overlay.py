#!/usr/bin/env python3
"""
gen_allied_dbc_overlay.py - emit 11_dbc_overlay.sql: the allied-race rows for the five
DBC stores the WORLDSERVER actually loads, as world-DB overlay rows.

WHY THIS EXISTS
This fork loads every DBC store as `file, THEN LoadFromDB(<table>_dbc)` (see
src/server/game/DataStores/DBCStores.cpp LOAD_DBC). The `*_dbc` tables ship empty and exist
precisely so content can be added without touching the worldserver's dbc directory. That is
far more reliable than copying .dbc files to the Linux box (and it is version-controlled).

The crash this fixes:
    ASSERT_NOTNULL_IMPL / LookupEntry(id)  at Unit::GetCollisionHeight (Unit.cpp ~17158)
    -> sCreatureDisplayInfoStore.AssertEntry(GetNativeDisplayId())
DBCStorage::LookupEntry returns nullptr for any id >= _indexTableSize, and the index table is
sized from the highest id in whatever the server loaded. Character CREATION never touches
CreatureDisplayInfo, which is why the pandaren could be created and then killed the server at
LOGIN.

NOT emitted, deliberately: CharSections / CharHairGeosets / CharacterFacialHairStyles /
CharBaseInfo have NO LOAD_DBC entry at all - they are client-only. Only the client needs them.

Sources (all already built and deployed client-side):
  Custom/CSV DBC/CreatureDisplayInfo.csv, CreatureModelData.csv   (columns == table columns)
  Custom/DBCs/ChrRaces.dbc, CharStartOutfit.dbc, SkillRaceClassInfo.dbc
"""
import csv
import io
import os
import re
import struct

REPO = r"K:\Dark-Chaos\DarkChaos-255-Master"
CSVDIR = os.path.join(REPO, "Custom", "CSV DBC")
DBCDIR = os.path.join(REPO, "Custom", "DBCs")
BASE = os.path.join(REPO, "data", "sql", "base", "db_world")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "11_dbc_overlay.sql")

RACES = (24, 25, 26)
CDI_IDS = (503912, 503913, 503914, 503915, 503916, 503917)
CMD_IDS = (503902, 503903, 503904, 503905, 503906, 503907)
PA, PH = 33554432, 25165824   # Alliance (KulTiran) / Horde (Vulpera+Zandalari)


def table_columns(name):
    s = io.open(os.path.join(BASE, name + ".sql"), encoding="utf-8", errors="replace").read()
    m = re.search(r"CREATE TABLE `%s` \((.*?)\n\) ENGINE" % name, s, re.S)
    return re.findall(r"^\s*`([^`]+)`", m.group(1), re.M)


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int,)):
        return str(v)
    if isinstance(v, float):
        return repr(v)
    s = str(v)
    if s == "":
        return "''"
    try:
        float(s)
        return s
    except ValueError:
        return "'" + s.replace("\\", "\\\\").replace("'", "''") + "'"


def read_dbc(path):
    d = open(path, "rb").read()
    magic, rows, fields, rsz, ssz = struct.unpack("<4siiii", d[:20])
    assert magic == b"WDBC"
    sb = d[20 + rows * rsz:]

    def s(o):
        if o <= 0:
            return ""
        return sb[o:sb.index(b"\0", o)].decode("latin-1")
    # NOTE: the record is rsz//4 INTS, which is not always the field count. CharStartOutfit
    # declares 77 fields but stores 74 ints - its race/class/sex/outfit is ONE packed int
    # that the DB table splits into four tinyint columns.
    n = rsz // 4
    recs = [struct.unpack("<%di" % n, d[20 + i * rsz:20 + (i + 1) * rsz]) for i in range(rows)]
    return recs, s, fields


def block(table, cols, rows, where, comment):
    out = ["-- " + comment,
           "DELETE FROM `%s` WHERE %s;" % (table, where),
           "INSERT INTO `%s` (%s) VALUES" % (table, ", ".join("`%s`" % c for c in cols))]
    out.append(",\n".join("(" + ", ".join(q(v) for v in r) + ")" for r in rows) + ";")
    return "\n".join(out)


def main():
    parts = ["-- Pandaren: DBC rows for the five stores the WORLDSERVER loads, delivered as",
             "-- world-DB overlay rows (DBCStores.cpp loads each store from file THEN from these",
             "-- tables). Generated by tools/gen_pandaren_dbc_overlay.py - do not hand-edit.",
             "--",
             "-- Fixes the login segfault: Unit::GetCollisionHeight ->",
             "-- sCreatureDisplayInfoStore.AssertEntry(503912..503917).",
             ""]

    # ---- creaturedisplayinfo_dbc / creaturemodeldata_dbc: CSV columns == table columns
    for table, csvname, ids in (("creaturedisplayinfo_dbc", "CreatureDisplayInfo.csv", CDI_IDS),
                                ("creaturemodeldata_dbc", "CreatureModelData.csv", CMD_IDS)):
        cols = table_columns(table)
        with open(os.path.join(CSVDIR, csvname), encoding="utf-8-sig", newline="") as f:
            rd = csv.reader(f)
            hdr = next(rd)
            assert [c.strip('"') for c in hdr] == cols, (table, hdr[:5], cols[:5])
            rows = [r for r in rd if r and int(r[0]) in ids]
        assert len(rows) == len(ids), (table, len(rows))
        parts.append(block(table, cols, rows,
                           "`ID` IN (%s)" % ", ".join(map(str, ids)),
                           "%s: the six allied-race display/model rows" % table))
        parts.append("")

    # ---- chrraces_dbc: 69 fields, string columns resolved from the dbc string block
    cols = table_columns("chrraces_dbc")
    recs, s, fields = read_dbc(os.path.join(DBCDIR, "ChrRaces.dbc"))
    assert fields == len(cols) == 69
    strcols = {i for i, c in enumerate(cols)
               if c in ("ClientPrefix", "ClientFilestring", "FacialHairCustomization_1",
                        "FacialHairCustomization_2", "HairCustomization")
               or "_Lang_" in c and not c.endswith("_Mask")}
    rows = []
    for r in recs:
        if r[0] in RACES:
            rows.append([s(v) if i in strcols else v for i, v in enumerate(r)])
    assert len(rows) == 3
    parts.append(block("chrraces_dbc", cols, rows,
                       "`ID` IN (24, 25, 26)", "chrraces_dbc: the three allied race rows"))
    parts.append("")

    # ---- charstartoutfit_dbc: dbc field 1 is a PACKED uint32 (race|class|sex|outfit bytes)
    #      that the table splits into four tinyint columns.
    cols = table_columns("charstartoutfit_dbc")
    recs, s, fields = read_dbc(os.path.join(DBCDIR, "CharStartOutfit.dbc"))
    rows = []
    for r in recs:
        packed = struct.pack("<i", r[1])
        if packed[0] in RACES:
            rows.append([r[0], packed[0], packed[1], packed[2], packed[3]] + list(r[2:]))
    assert rows and len(rows[0]) == len(cols), (len(rows[0]) if rows else 0, len(cols))
    parts.append(block("charstartoutfit_dbc", cols, rows,
                       "`RaceID` IN (24, 25, 26)",
                       "charstartoutfit_dbc: %d starting-outfit rows" % len(rows)))
    parts.append("")

    # ---- skillraceclassinfo_dbc: the rows whose RaceMask we swept for the new race bits
    cols = table_columns("skillraceclassinfo_dbc")
    recs, s, fields = read_dbc(os.path.join(DBCDIR, "SkillRaceClassInfo.dbc"))
    assert fields == len(cols) == 8
    rows = [list(r) for r in recs if r[2] > 0 and (r[2] & (PA | PH))]
    parts.append(block("skillraceclassinfo_dbc", cols, rows,
                       "`ID` IN (%s)" % ", ".join(str(r[0]) for r in rows),
                       "skillraceclassinfo_dbc: %d rows re-masked so the allied races may train them" % len(rows)))
    parts.append("")

    io.open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(parts))
    print("wrote %s" % os.path.abspath(OUT))


if __name__ == "__main__":
    main()
