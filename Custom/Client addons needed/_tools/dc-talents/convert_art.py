def resolve_sheets(patterns, atlas_info):
    if not patterns:
        return list(DEFAULT_SHEETS), []
    chosen, unknown = [], []
    lower_keys = {k.lower(): k for k in atlas_info}
    for pat in patterns:
        p = pat.replace('\\', '/')
        is_glob = any(c in p for c in '*?[')
        field = (lambda k: k.lower()) if '/' in p else (lambda k: k.rsplit('/', 1)[-1].lower())
        if not is_glob:
            hits = [k for k in atlas_info if field(k) == p.lower()]
            if not hits and p.lower() in lower_keys:
                hits = [lower_keys[p.lower()]]
        else:
            hits = [k for k in atlas_info if fnmatch.fnmatchcase(field(k), p.lower())
                    and not any(fnmatch.fnmatchcase(k.lower(), g.lower()) for g in SKIP_GLOBS)]
        if not hits:
            unknown.append(pat)
        chosen += [k for k in sorted(hits) if k not in chosen]
    return chosen, unknown


def fmt_psnr(v):
    if v is None:
        return '-'
    if v == 'inf' or (isinstance(v, float) and math.isinf(v)):
        return 'exact'
    return f'{v:.2f}'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--sheets', nargs='+', metavar='SHEET',
                    help='retail sheet keys (Interface/TalentFrame/Talents) or basenames (Talents); globs allowed. '
                         'Default: the full DC-Talents set.')
    ap.add_argument('--dry-run', action='store_true', help='analyse and report, write nothing')
    ap.add_argument('--verify-only', action='store_true', help='re-verify already written outputs, write nothing')
    ap.add_argument('--src-root', default=DEFAULT_SRC_ROOT)
    ap.add_argument('--atlas', default=DEFAULT_ATLAS)
    ap.add_argument('--stage-root', default=DEFAULT_STAGE)
    ap.add_argument('--lua-out', default=DEFAULT_LUA)
    ap.add_argument('--manifest', default=DEFAULT_MANIFEST)
    ap.add_argument('--alpha-scope', choices=('atlas', 'sheet'), default='atlas',
                    help='measure translucency over the atlas rects (+1 texel apron) or the whole sheet')
    ap.add_argument('--mips', choices=('auto', 'on', 'off'), default='auto',
                    help='auto mirrors the source: full chain to 1x1 when it had one, else mip 0 only')
    ap.add_argument('--jobs', type=int, default=min(8, os.cpu_count() or 1))
    args = ap.parse_args(argv)

    atlas_info = parse_atlas_info(args.atlas)
    keys, unknown = resolve_sheets(args.sheets, atlas_info)
    manifest = load_manifest(args.manifest)
    owned = {rel.lower(): (rel, e) for rel, e in manifest['outputs'].items()}
    stage = os.path.abspath(args.stage_root)

    missing, collisions, jobs = [], [], []
    for key in keys:
        if key not in atlas_info:
            missing.append(f'{key}: not in {os.path.basename(args.atlas)}')
            continue
        src = source_path(args.src_root, key)
        if not src:
            missing.append(f'{key}: no source BLP under {args.src_root}')
            continue
        parts = key.split('/')
        real_dir = find_ci(stage, parts[:-1])
        out_dir = real_dir or os.path.join(stage, *parts[:-1])
        existing = find_ci(out_dir, [IN_PLACE.get(key, parts[-1] + '.blp')]) if real_dir else None
        name = os.path.basename(existing) if existing else IN_PLACE.get(key, parts[-1] + '.blp')
        out = os.path.join(out_dir, name)
        rel = os.path.relpath(out, stage).replace('\\', '/')
        state, backup = 'new', None
        if existing:
            cur_sha = _sha256(read_bytes(existing))
            prev = owned.get(rel.lower())
            if prev and prev[1].get('sha256') == cur_sha:
                state = 'ours'
            elif key in IN_PLACE:
                try:
                    orig = BlpInfo(read_bytes(existing))
                    orig_desc = f'enc {orig.enc}, {orig.width}x{orig.height}'
                except ValueError as exc:
                    orig, orig_desc = None, str(exc)
                backup = os.path.join(stage, BACKUP_DIR, *rel.split('/'))
                if orig is None or orig.enc != 3:
                    state = 'COLLISION'
                    collisions.append(f'{rel}: in-place replacement is only authorised for colorEncoding 3 '
                                      f'originals, found {orig_desc}')
                elif os.path.exists(backup) and _sha256(read_bytes(backup)) != cur_sha:
                    state = 'COLLISION'
                    collisions.append(f'{rel}: backup {os.path.relpath(backup, stage)} exists with different bytes')
                else:
                    state = f'replace ({orig_desc}) -> backup'
            else:
                state = 'COLLISION'
                collisions.append(f'{rel}: already exists as {os.path.relpath(existing, stage)} '
                                  f'and was not written by this tool')
        jobs.append(dict(key=key, src=src, out=out, rel=rel, state=state, backup=backup,
                         atlases=atlas_info[key], alpha_scope=args.alpha_scope, mips=args.mips,
                         dry_run=args.dry_run or args.verify_only))

    lua_existing = os.path.exists(args.lua_out)
    if lua_existing:
        with open(args.lua_out, encoding='utf-8', errors='replace') as f:
            first = f.readline().rstrip('\r\n')
        if first != LUA_HEADER:
            collisions.append(f'{args.lua_out}: exists and is not generated by this tool')

    # duplicate atlas names across everything the Lua table will hold
    lua_keys = {j['key'] for j in jobs} | {e['sheet'] for e in manifest['outputs'].values() if e.get('sheet')}
    seen = {}
    for k in sorted(k for k in lua_keys if k in atlas_info):
        for n in atlas_info[k]:
            if n in seen:
                collisions.append(f'atlas "{n}" exists in both {seen[n]} and {k}')
            seen[n] = k

    print(f'convert_art: {len(jobs)} sheet(s), stage {stage}')
    for j in jobs:
        print(f'  {j["key"]:58s} <- {os.path.relpath(j["src"], args.src_root)}  [{j["state"]}]')
    for m in missing:
        print(f'  MISSING {m}')
    for u in unknown:
        print(f'  UNKNOWN --sheets pattern: {u}')
    if collisions:
        print('\nSTOP - name collisions, nothing was written:')
        for c in collisions:
            print(f'  COLLISION {c}')
        return 3

    if args.verify_only:
        jobs = [j for j in jobs if j['state'] == 'ours']
        if not jobs:
            print('nothing to verify (no outputs of this tool in the stage tree)')
            return 1

    results = {}
    t0 = time.time()
    with cf.ProcessPoolExecutor(max_workers=max(1, args.jobs)) as pool:
        for res in pool.map(convert_sheet, jobs):
            results[res['key']] = res
    print(f'\nanalysed{"" if args.dry_run or args.verify_only else " + encoded"} in {time.time() - t0:.1f}s')
    errors = [(k, r['error']) for k, r in results.items() if 'error' in r]
    if errors:
        print('STOP - conversion failed, nothing was written:')
        for k, e in errors:
            print(f'  ERROR {k}: {e}')
        return 5

    if args.dry_run:
        total = 0
        for j in jobs:
            r = results[j['key']]
            a = r['analysis']
            total += r['bytes']
            print(f'  {j["rel"]:62s} {r["width"]:>4}x{r["height"]:<4} {r["format"]} mips {r["mips"]} '
                  f'{r["bytes"]:>9} B  {r["mode"]:11s} translucent {a["alpha_lt250_fraction"]:.4f} '
                  f'(sheet {a["alpha_lt250_fraction_sheet"]:.4f})  empty rects {len(a["empty_rects"])}')
        print(f'  total {total} bytes ({total / 1048576:.1f} MiB)')
        return 2 if missing or unknown else 0

    written = []
    if not args.verify_only:
        for j in jobs:
            r = results[j['key']]
            if j['backup'] and not os.path.exists(j['backup']):
                os.makedirs(os.path.dirname(j['backup']), exist_ok=True)
                shutil.copy2(j['out'], j['backup'])
                if _sha256(read_bytes(j['backup'])) != _sha256(read_bytes(j['out'])):
                    print(f'STOP - backup copy of {j["rel"]} does not match the original')
                    return 4
            if os.path.exists(j['out']) and _sha256(read_bytes(j['out'])) == r['sha256']:
                j['action'] = 'unchanged'
            else:
                write_atomic(j['out'], r['blob'])
                j['action'] = 'written'
                written.append(j['rel'])
            r.pop('blob', None)

    verify_jobs = [dict(key=j['key'], out=j['out'], src=j['src'], format=results[j['key']]['format'],
                        width=results[j['key']]['width'], height=results[j['key']]['height'],
                        mips=results[j['key']]['mips']) for j in jobs]
    with cf.ProcessPoolExecutor(max_workers=max(1, args.jobs)) as pool:
        checks = {c['key']: c for c in pool.map(verify_output, verify_jobs)}

    failed = []
    for j in jobs:
        r, c = results[j['key']], checks[j['key']]
        if c['problems']:
            failed.append((j['rel'], c['problems']))
        if not args.verify_only and c.get('sha256') != r.get('sha256'):
            failed.append((j['rel'], ['file on disk does not match the encoded bytes']))

    # manifest + Lua (a failed verification keeps the previous manifest entry out of the Lua)
    for j in jobs:
        r, c = results[j['key']], checks[j['key']]
        if c['problems']:
            continue
        prev = owned.get(j['rel'].lower(), (None, {}))[1]
        entry = dict(sheet=j['key'], source=os.path.relpath(j['src'], args.src_root).replace('\\', '/'),
                     source_sha256=r['src_sha256'], sha256=c['sha256'], bytes=os.path.getsize(j['out']),
                     width=r['width'], height=r['height'], format=r['format'], mips=r['mips'], mode=r['mode'],
                     alpha_scope=args.alpha_scope, alpha_lt250_fraction=r['analysis']['alpha_lt250_fraction'],
                     atlases=len(atlas_info[j['key']]),
                     psnr_rgb_visible=_jsonable(c['psnr_rgb_visible']), psnr_rgb_all=_jsonable(c['psnr_rgb_all']),
                     psnr_alpha=_jsonable(c['psnr_alpha']))
        if j['backup']:
            orig = BlpInfo(read_bytes(j['backup']))
            entry['replaced_original'] = dict(backup=os.path.relpath(j['backup'], stage).replace('\\', '/'),
                                              sha256=_sha256(read_bytes(j['backup'])), encoding=orig.enc,
                                              width=orig.width, height=orig.height)
        elif 'replaced_original' in prev:
            entry['replaced_original'] = prev['replaced_original']
        for old_rel in [k for k in manifest['outputs'] if k.lower() == j['rel'].lower()]:
            del manifest['outputs'][old_rel]
        manifest['outputs'][j['rel']] = entry

    gone = [rel for rel in manifest['outputs'] if not os.path.exists(os.path.join(stage, *rel.split('/')))]
    for rel in gone:
        print(f'  note: {rel} is in the manifest but no longer staged - dropped from the Lua table')
        del manifest['outputs'][rel]
    shipped = {e['sheet']: (e['width'], e['height']) for e in manifest['outputs'].values()
               if e['sheet'] in atlas_info}
    lua_bytes = render_lua(shipped, atlas_info)
    lua_action = 'unchanged'
    if not args.verify_only and (not lua_existing or read_bytes(args.lua_out) != lua_bytes):
        write_atomic(args.lua_out, lua_bytes)
        lua_action = 'written'
    try:
        lua_rel = os.path.relpath(args.lua_out, CUSTOM_DIR)
    except ValueError:   # different drive
        lua_rel = os.path.abspath(args.lua_out)
    manifest['lua'] = dict(path=lua_rel.replace('\\', '/'),
                           sha256=_sha256(lua_bytes), sheets=len(shipped),
                           atlases=sum(len(atlas_info[k]) for k in shipped))
    manifest['generator'] = '_tools/dc-talents/convert_art.py'
    if not args.verify_only:
        mbytes = (json.dumps(manifest, indent=2, sort_keys=True) + '\n').encode('utf-8')
        if not os.path.exists(args.manifest) or read_bytes(args.manifest) != mbytes:
            write_atomic(args.manifest, mbytes)

    # report
    print(f'\n{"output (under stage root)":62s} {"size":>9} {"fmt":4} {"mips":>4} {"bytes":>9} '
          f'{"b8":>2} {"b11":>3} {"RGBvis":>6} {"RGBall":>6} {"alpha":>6} {"atl":>3}  mode / action')
    total = 0
    for j in sorted(jobs, key=lambda j: j['rel'].lower()):
        r, c = results[j['key']], checks[j['key']]
        size = os.path.getsize(j['out'])
        total += size
        print(f'{j["rel"]:62s} {r["width"]:>4}x{r["height"]:<4} {r["format"]:4} {r["mips"]:>4} {size:>9} '
              f'{c.get("byte8", "?"):>2} {c.get("byte11", "?"):>3} {fmt_psnr(c.get("psnr_rgb_visible")):>6} '
              f'{fmt_psnr(c.get("psnr_rgb_all")):>6} {fmt_psnr(c.get("psnr_alpha")):>6} '
              f'{len(atlas_info[j["key"]]):>3}  {r["mode"]} / {j.get("action", "verified")}')
    print(f'total {len(jobs)} files, {total} bytes ({total / 1048576:.2f} MiB); Lua {lua_action}: '
          f'{manifest["lua"]["sheets"]} sheets, {manifest["lua"]["atlases"]} atlases -> {args.lua_out}')
    for j in jobs:
        a = results[j['key']]['analysis']
        if a['empty_rects']:
            print(f'  WARN {j["key"]}: {len(a["empty_rects"])} atlas rect(s) hold no visible texel: '
                  f'{", ".join(a["empty_rects"][:5])}')
        if a['visible_outside_rects']:
            print(f'  note {j["key"]}: {a["visible_outside_rects"]} visible texels lie outside every atlas rect '
                  f'({a["visible_outside_rects"] / max(1, a["visible_total"]):.2%} of visible)')
        if results[j['key']]['format'] == 'DXT1' and a['alpha_lt250_texels_in_scope']:
            print(f'  note {j["key"]}: DXT1 drops alpha on {a["alpha_lt250_texels_in_scope"]} translucent texels')
    for rel, probs in failed:
        for p in probs:
            print(f'  FAIL {rel}: {p}')
    for m in missing:
        print(f'  MISSING {m}')
    if failed:
        return 5
    return 2 if missing or unknown else 0


