def render_lua(shipped, atlas_info):
    """shipped: {sheet key: (width, height)}; atlas_info: parsed AtlasInfo.lua."""
    keys = sorted(shipped, key=lambda k: (k.lower(), k))
    lines = [LUA_HEADER, 'local _, ns = ...', '',
             '-- Pixel size of each shipped sheet (runtime path without extension).',
             'ns.AtlasSheets = {']
    lines += [f'    ["{lua_path(k)}"] = {{ {shipped[k][0]}, {shipped[k][1]} }},' for k in keys]
    lines += ['}', '',
              '-- atlas = { file, width, height, left, right, top, bottom, tilesH, tilesV } (retail values verbatim;',
              '-- width/height are the logical UI size, which can be smaller than the texel rect on hi-res art).',
              'ns.AtlasInfo = {']
    for k in keys:
        names = sorted(atlas_info[k], key=lambda n: (n.lower(), n))
        lines.append(f'    -- {k}: {len(names)} atlases')
        for n in names:
            a = atlas_info[k][n]
            lines.append(f'    ["{n}"] = {{ "{lua_path(k)}", {a.width}, {a.height}, {", ".join(a.uv)}, '
                         f'{a.tiles_h}, {a.tiles_v} }},')
    lines += ['}', '',
              '-- Retail sheet each atlas was taken from (Helix/AtlasInfo.lua key), for coverage audits.',
              'ns.AtlasSourceSheet = {']
    for k in keys:
        for n in sorted(atlas_info[k], key=lambda n: (n.lower(), n)):
            lines.append(f'    ["{n}"] = "{k}",')
    lines += ['}', '']
    return '\n'.join(lines).encode('utf-8')


