def _sha256(data):
    return hashlib.sha256(data).hexdigest()


def convert_sheet(job):
    try:
        return _convert_sheet(job)
    except Exception as exc:  # noqa: BLE001 - reported per sheet by main()
        return dict(key=job['key'], error=f'{type(exc).__name__}: {exc}')


def _convert_sheet(job):
    """Worker: load source, decide format, encode (unless dry run). Returns a result dict."""
    t0 = time.time()
    with open(job['src'], 'rb') as f:
        src_blob = f.read()
    info, rgba = decode_blp_mip0(src_blob)
    ana = analyse(rgba, job['atlases'], job['alpha_scope'])
    fmt = ana['format']
    w, h = info.width, info.height
    src_chain = info.has_mips != 0 and info.mip_count > 1
    want_chain = src_chain if job['mips'] == 'auto' else job['mips'] == 'on'
    if want_chain and (w & (w - 1) or h & (h - 1)):
        raise ValueError(f'{w}x{h} is not a power of two; cannot build a mip chain')
    nlev = chain_length(w, h) if want_chain else 1
    passthrough = (info.fmt == fmt and (fmt == 'DXT5' or info.alpha_depth == 0)
                   and info.mip_count >= nlev
                   and all(info.sizes[i] == dxt_size(max(1, w >> i), max(1, h >> i), fmt) for i in range(nlev)))
    res = dict(key=job['key'], format=fmt, width=w, height=h, mips=nlev, analysis=ana,
               src_sha256=_sha256(src_blob), src_enc=info.enc, src_has_mips=info.has_mips,
               src_mip_count=info.mip_count, mode='passthrough' if passthrough else 'encoded')
    sizes = [dxt_size(max(1, w >> i), max(1, h >> i), fmt) for i in range(nlev)]
    res['bytes'] = HEADER_SIZE + PALETTE_SIZE + sum(sizes)
    if job['dry_run']:
        res['seconds'] = round(time.time() - t0, 2)
        return res
    if passthrough:
        levels = [info.level_bytes(src_blob, i) for i in range(nlev)]
        if fmt == 'DXT5':
            levels = [normalise_dxt5_level(lv) for lv in levels]
    else:
        levels, cur = [], rgba
        for i in range(nlev):
            if i:
                cur = downsample(cur)
            levels.append(encode_dxt(cur, fmt))
    blob = build_blp(w, h, fmt, levels)
    assert len(blob) == res['bytes']
    res['blob'] = blob
    res['sha256'] = _sha256(blob)
    res['seconds'] = round(time.time() - t0, 2)
    return res


def _psnr(a, b):
    if a.size == 0:
        return None
    mse = float(np.mean((a.astype(np.float64) - b.astype(np.float64)) ** 2))
    return math.inf if mse == 0 else 10 * math.log10(255.0 * 255.0 / mse)


def _dds_wrap(data, w, h, fmt):
    pf = struct.pack('<II4sIIIII', 32, 0x4, fmt.encode('ascii'), 0, 0, 0, 0, 0)
    body = struct.pack('<IIIIIII', 124, 0x1 | 0x2 | 0x4 | 0x1000 | 0x80000, h, w, len(data), 0, 0)
    body += bytes(44) + pf + struct.pack('<IIIII', 0x1000, 0, 0, 0, 0)
    return b'DDS ' + body + data


def verify_output(job):
    try:
        return _verify_output(job)
    except Exception as exc:  # noqa: BLE001 - reported per sheet by main()
        return dict(key=job['key'], problems=[f'verification crashed: {type(exc).__name__}: {exc}'])


def _verify_output(job):
    """Worker: read the written file back from disk, check the header, decode mip 0, compare with the source."""
    problems = []
    with open(job['out'], 'rb') as f:
        blob = f.read()
    fmt, w, h, nlev = job['format'], job['width'], job['height'], job['mips']
    try:
        info = BlpInfo(blob)
    except ValueError as exc:
        return dict(key=job['key'], problems=[str(exc)])
    want = {
        'type': (info.btype, 1), 'byte8 colorEncoding': (blob[8], 2),
        'byte9 alphaDepth': (blob[9], 8 if fmt == 'DXT5' else 0),
        'byte10 alphaType': (blob[10], 7 if fmt == 'DXT5' else 0),
        'byte11 hasMips': (blob[11], 1 if nlev > 1 else 0), 'width': (info.width, w), 'height': (info.height, h),
        'mip count': (info.mip_count, nlev),
    }
    problems += [f'{k} is {got}, expected {exp}' for k, (got, exp) in want.items() if got != exp]
    if blob[11] not in (0, 1):
        problems.append(f'hasMips byte is {blob[11]} (3.3.5 accepts 0/1 only)')
    pos = HEADER_SIZE + PALETTE_SIZE
    for i in range(16):
        exp_size = dxt_size(max(1, w >> i), max(1, h >> i), fmt) if i < nlev else 0
        exp_off = pos if i < nlev else 0
        if (info.offsets[i], info.sizes[i]) != (exp_off, exp_size):
            problems.append(f'mip {i}: offset/size {info.offsets[i]}/{info.sizes[i]}, expected {exp_off}/{exp_size}')
        pos += exp_size if i < nlev else 0
    if len(blob) != pos:
        problems.append(f'file is {len(blob)} bytes, mip table ends at {pos}')
    if blob[HEADER_SIZE:HEADER_SIZE + PALETTE_SIZE] != bytes(PALETTE_SIZE):
        problems.append('palette block is not zeroed')
    if problems:
        return dict(key=job['key'], problems=problems)
    mip0 = info.level_bytes(blob, 0)
    dec = decode_dxt(mip0, w, h, fmt)
    with open(job['src'], 'rb') as f:
        _, src = decode_blp_mip0(f.read())
    vis = src[..., 3] > 0
    stats = dict(
        byte8=blob[8], byte11=blob[11],
        psnr_rgb_visible=_psnr(dec[..., :3][vis], src[..., :3][vis]),
        psnr_rgb_all=_psnr(dec[..., :3], src[..., :3]),
        psnr_alpha=_psnr(dec[..., 3], src[..., 3]) if fmt == 'DXT5' else None,
    )
    ch = slice(0, 4) if fmt == 'DXT5' else slice(0, 3)
    # independent decoder 1: Pillow's C BCn decoder on the same block data
    try:
        with Image.open(io.BytesIO(_dds_wrap(mip0, w, h, fmt))) as im:
            ref = np.asarray(im.convert('RGBA'))
        stats['dds_maxdiff'] = int(np.abs(ref[..., ch].astype(np.int32) - dec[..., ch]).max())
        if stats['dds_maxdiff'] > DDS_TOL:
            problems.append(f"Pillow DDS decoder differs by {stats['dds_maxdiff']} (> {DDS_TOL})")
    except Exception as exc:  # noqa: BLE001
        problems.append(f'Pillow DDS decode failed: {exc}')
    # independent decoder 2: Pillow's BLP2 reader on the file itself (header + container end to end)
    try:
        with Image.open(io.BytesIO(blob)) as im:
            if im.format != 'BLP' or im.size != (w, h):
                problems.append(f'Pillow BLP reader sees {im.format} {im.size}')
            ref = np.asarray(im.convert('RGBA'))
        drgb = int(np.abs(ref[..., :3].astype(np.int32) - dec[..., :3]).max())
        da = int(np.abs(ref[..., 3].astype(np.int32) - dec[..., 3]).max()) if fmt == 'DXT5' else 0
        stats['blp_maxdiff'] = max(drgb, da)
        if drgb > BLP_TOL_RGB or da > BLP_TOL_A:
            problems.append(f'Pillow BLP reader differs by rgb {drgb} / alpha {da}')
    except Exception as exc:  # noqa: BLE001
        problems.append(f'Pillow BLP read failed: {exc}')
    stats['sha256'] = _sha256(blob)
    return dict(key=job['key'], problems=problems, **stats)


# ------------------------------------------------------------------------------------------------ files & paths

def find_ci(root, parts):
    """Resolve a relative path case-insensitively below root; None when any part is missing."""
    cur = root
    for part in parts:
        try:
            entries = os.listdir(cur)
        except OSError:
            return None
        hit = [e for e in entries if e.lower() == part.lower()]
        if not hit:
            return None
        cur = os.path.join(cur, sorted(hit)[0])
    return cur


def source_path(src_root, key):
    parts = key.split('/')
    if parts[0].lower() == 'interface':
        parts = parts[1:]
    parts[-1] += '.blp'
    return find_ci(src_root, parts) or find_ci(src_root, ['Interface'] + parts)


def write_atomic(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + '.tmp-convert_art'
    with open(tmp, 'wb') as f:
        f.write(data)
    os.replace(tmp, path)


