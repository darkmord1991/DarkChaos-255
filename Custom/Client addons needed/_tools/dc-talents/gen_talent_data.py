"""Generate DC-Talents/Data/TalentData.lua from the server Talent.dbc, TalentTab.dbc and Spell.dbc.

The 3.3.5 client API exposes talents by (tab, index) and never returns spell IDs, so the ported
retail talent UI gets the rank spells and the "grants an active ability" flag (circle node vs
square node) from this table, keyed by Talent.dbc ID (the ID in |Htalent:ID:rank| links).

Usage: python gen_talent_data.py [--dbc DIR] [--out FILE]
"""
import argparse
import os
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_DBC = r'K:/Dark-Chaos/Server/data/dbc'
DEFAULT_OUT = os.path.normpath(os.path.join(HERE, '..', '..', 'DC-Talents', 'Data', 'TalentData.lua'))

SPELL_ATTR0_PASSIVE = 0x40
SPELL_EFFECT_LEARN_SPELL = 36


def load_dbc(path):
    data = open(path, 'rb').read()
    magic, count, fields, size, strsize = struct.unpack_from('<4s4I', data, 0)
    assert magic == b'WDBC', path
    rows = [struct.unpack_from('<%dI' % fields, data, 20 + i * size) for i in range(count)]
    strings = data[20 + count * size:]
    return rows, strings, fields


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dbc', default=DEFAULT_DBC)
    ap.add_argument('--out', default=DEFAULT_OUT)
    args = ap.parse_args()

    talents, _, tf = load_dbc(os.path.join(args.dbc, 'Talent.dbc'))
    tabs, tab_strings, tabf = load_dbc(os.path.join(args.dbc, 'TalentTab.dbc'))
    spells, _, sf = load_dbc(os.path.join(args.dbc, 'Spell.dbc'))
    assert tf == 23 and sf == 234 and tabf == 24, (tf, sf, tabf)

    spell_by_id = {row[0]: row for row in spells}

    def is_passive(spell_id):
        row = spell_by_id.get(spell_id)
        return row is None or bool(row[4] & SPELL_ATTR0_PASSIVE)

    def grants_active(spell_id):
        row = spell_by_id.get(spell_id)
        if row is None:
            return False
        if not row[4] & SPELL_ATTR0_PASSIVE:
            return True
        for i in range(3):
            if row[71 + i] == SPELL_EFFECT_LEARN_SPELL and not is_passive(row[116 + i]):
                return True
        return False

    # TalentTab: 0 ID, 1-17 Name_lang, 18 SpellIconID, 19 RaceMask, 20 ClassMask,
    # 21 CategoryEnumID (pet talent mask), 22 OrderIndex, 23 BackgroundFile
    tab_info = {row[0]: (row[20], row[21], row[22]) for row in tabs}

    lines = []
    for row in sorted(talents, key=lambda r: r[0]):
        talent_id, tab_id, tier, column = row[0], row[1], row[2], row[3]
        ranks = [s for s in row[4:13] if s]
        if not ranks or tab_id not in tab_info:
            continue
        active = 1 if grants_active(ranks[0]) else 0
        # Talent.dbc PrereqTalent[0] / PrereqRank[0]: the prerequisite must be at PrereqRank+1 or higher
        # (Player::LearnTalent walks RankID[DependsOnRank..] of the prerequisite).
        prereq, prereq_rank = row[13], row[16] + 1 if row[13] else 0
        lines.append('    [%d] = { %d, %d, %d, %d, %d, %d, %s },' % (
            talent_id, tab_id, tier, column, active, prereq, prereq_rank, ', '.join(str(s) for s in ranks)))

    tab_lines = []
    for tab_id in sorted(tab_info):
        class_mask, pet_mask, order = tab_info[tab_id]
        tab_lines.append('    [%d] = { %d, %d, %d },' % (tab_id, class_mask, pet_mask, order))

    out = [
        '-- Generated by _tools/dc-talents/gen_talent_data.py from the server Talent.dbc,',
        '-- TalentTab.dbc and Spell.dbc. Do not edit by hand; rerun the script instead.',
        'local _, ns = ...',
        '',
        '-- [talentID] = { talentTabID, tier (0-based), column (0-based), grantsActiveAbility (1/0),',
        '--                prereqTalentID (0 = none), prereqRequiredRank (1-based), rank1SpellID, rank2SpellID, ... }',
        'ns.TalentData = {',
        *lines,
        '}',
        '',
        '-- [talentTabID] = { classMask, petTalentMask, orderIndex }',
        'ns.TalentTabData = {',
        *tab_lines,
        '}',
        '',
    ]
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w', encoding='utf8', newline='\n') as fh:
        fh.write('\n'.join(out))
    print('wrote', args.out, len(lines), 'talents,', len(tab_lines), 'tabs')


if __name__ == '__main__':
    main()
