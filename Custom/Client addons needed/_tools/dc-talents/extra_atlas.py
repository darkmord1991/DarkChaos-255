"""Emit DC-Talents/Data/AtlasExtra.lua: retail atlas entries for sheets the DC client patch ALREADY
ships (staged by other work) with the retail layout, so convert_art.py must not re-encode them.

Atlas UVs are normalised, so a sheet staged at a different resolution with the same layout (for
example NewPlayerExperienceParts at half size) still works. Check the layout before adding a sheet.
Usage: python extra_atlas.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.normpath(os.path.join(HERE, '..', '..', 'DC-Talents'))
ATLAS_SOURCE = r'K:/Dark-Chaos/WoW 11.2.7 FrameXML/Helix/AtlasInfo.lua'

# Retail sheet key -> staged file (runtime path, no extension). Verified 2026-09-30:
#   Common/Search                  staged 512x128 DXT5 == retail 512x128
#   HelpFrame/NewPlayerExperienceParts staged 1024x512 DXT5, retail 2048x1024 (same layout, half size)
EXISTING_SHEETS = {
    'Interface/Common/Search': 'Interface\\\\Common\\\\Search',
    'Interface/HelpFrame/NewPlayerExperienceParts': 'Interface\\\\HelpFrame\\\\NewPlayerExperienceParts',
}


def main():
    entries = []
    sheet = None
    for line in open(ATLAS_SOURCE, encoding='utf-8', errors='replace'):
        m = re.match(r'\s*\["(Interface/[^"]+)"\]=\{', line)
        if m:
            sheet = m.group(1)
            continue
        if sheet not in EXISTING_SHEETS:
            continue
        m = re.match(r'\s*\["([^"]+)"\]=\{(\d+), (\d+), ([\d.e-]+), ([\d.e-]+), ([\d.e-]+), ([\d.e-]+), (true|false), (true|false)', line)
        if m:
            name, w, h, l, r, t, b, th, tv = m.groups()
            entries.append('    ["%s"] = { "%s", %s, %s, %s, %s, %s, %s, %s, %s },' % (
                name, EXISTING_SHEETS[sheet], w, h, l, r, t, b, th, tv))

    out = [
        '-- Generated by _tools/dc-talents/extra_atlas.py: retail 11.2.7 atlas entries for sheets the DC client',
        '-- patch already ships with the retail layout. Do not edit by hand; rerun the script.',
        'local _, ns = ...',
        '',
        'ns.AtlasInfo = ns.AtlasInfo or {}',
        'for name, data in pairs({',
        *sorted(entries),
        '}) do',
        '    ns.AtlasInfo[name] = ns.AtlasInfo[name] or data',
        'end',
        '',
    ]
    path = os.path.join(ADDON, 'Data', 'AtlasExtra.lua')
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(out))
    print('wrote', path, len(entries), 'atlases')


if __name__ == '__main__':
    main()
